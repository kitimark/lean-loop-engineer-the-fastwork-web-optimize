test("re-entrancy: a nested call runs inside the caller's slot", () => {
  const { d, env } = scratch();
  try {
    const r = spawnSync("sh", [wrapper, "sh", wrapper, "sh", "-c", probe], { env, encoding: "utf8" });
    assert.equal(r.stdout.trim(), "0 unset");
    assert.equal(run({ ...env, LAKE_SLOT: "1" }, probe).stdout.trim(), "1 unset");
  } finally { rmSync(d, { recursive: true, force: true }); }
});

test("concurrent builds: the second gets slot 1 with the capped pool, a third waits until a slot frees", async () => {
  const { d, env } = scratch();
  try {
    const a = hold(env, d, "a");
    await until(() => a.out() !== null);
    assert.equal(a.out(), "0 unset");
    const second = run(env, probe);
    assert.equal(second.stdout.trim(), `1 ${pools[1]}`);
    assert.match(second.stderr, /lake-slot: slot 1, pool 4/);
    const b = hold(env, d, "b");
    await until(() => b.out() !== null);
    assert.equal(b.out(), `1 ${pools[1]}`);
    assert.equal(existsSync(join(d, "timings.jsonl")), false);
    const c = hold(env, d, "c");
    await new Promise((r) => setTimeout(r, 1500));
    assert.equal(c.out(), null);
    a.release();
    assert.equal(await a.done, 0);
    await until(() => c.out() !== null);
    assert.equal(c.out(), "0 unset");
    b.release(); c.release();
    assert.equal(await b.done, 0);
    assert.equal(await c.done, 0);
    const spans = readFileSync(join(d, "timings.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
    assert.deepEqual(spans.map((x) => [x.tool, x.step, x.exit]), [["lake-slot", "wait", 0]]);
    assert.ok(spans[0].durMs >= 1000, `waited ${spans[0].durMs} ms`);
  } finally { rmSync(d, { recursive: true, force: true }); }
});

test("without LAKE_SLOT_DIR the slot files live under the git common dir, from the main checkout and from a worktree", () => {
  const d = mkdtempSync(join(tmpdir(), "lake-slot-git-"));
  try {
    const git = (cwd, ...a) => assert.equal(spawnSync("git", a, { cwd, encoding: "utf8" }).status, 0);
    const main = join(d, "main");
    const lay = (r) => {
      mkdirSync(join(r, "scripts"), { recursive: true });
      mkdirSync(join(r, "packages/contracts/golden/sched"), { recursive: true });
      copyFileSync(wrapper, join(r, "scripts/lake-slot.sh"));
      copyFileSync(lib, join(r, "scripts/lake-slot-lib.sh"));
      writeFileSync(join(r, "packages/contracts/golden/sched/lake-slot.gen.sh"), genText);
    };
    mkdirSync(main);
    git(main, "init", "-q");
    git(main, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "x");
    git(main, "worktree", "add", "-q", join(d, "wt"));
    lay(main); lay(join(d, "wt"));
    const { LAKE_SLOT_DIR: _, LAKE_SLOT: __, FW_LOCK_EVENTS: ___, FW_LOCK_EVENTS_FILE: ____, CI: _____, ...env } = process.env;
    for (const r of [main, join(d, "wt")]) {
      const p = spawnSync("sh", [join(r, "scripts/lake-slot.sh"), "sh", "-c", probe], { cwd: d, env, encoding: "utf8" });
      assert.equal(p.status, 0, p.stderr);
      assert.match(p.stdout, /^0 /);
    }
    assert.equal(existsSync(join(main, ".git/lake-slot/0")), true);
    assert.equal(existsSync(join(d, "wt/.git/lake-slot")), false);
  } finally { rmSync(d, { recursive: true, force: true }); }
});

