// node --test scripts/lake-slot.test.mjs (task lake-build-slots): scripts/lake-slot.sh and scripts/lake-slot-lib.sh on a
// scratch slot directory.
// Plain JS on purpose: lean.yml runs it on Linux (the flock branch) with the runner's stock node; apps/runner's
// test/ci-triggers.test.ts runs it on a land.
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const top = join(dirname(fileURLToPath(import.meta.url)), "..");
const wrapper = join(top, "scripts/lake-slot.sh");
const lib = join(top, "scripts/lake-slot-lib.sh");
const genText = readFileSync(join(top, "packages/contracts/golden/sched/lake-slot.gen.sh"), "utf8");
const gen = Object.fromEntries(genText.split("\n").filter((l) => /^[A-Z_]+=/.test(l)).map((l) => {
  const [k, v] = l.split(/=(.*)/s);
  return [k, v.replace(/^'|'$/g, "")];
}));
const pools = gen.LAKE_SLOT_POOLS.split(" ");
const probe = 'echo "$LAKE_SLOT ${LEAN_NUM_THREADS-unset}"';

const scratch = () => {
  const d = mkdtempSync(join(tmpdir(), "lake-slot-test-"));
  const { LEAN_NUM_THREADS: _, LAKE_SLOT: __, FW_TIMINGS_FILE: ___, FW_LOCK_EVENTS: ____, FW_LOCK_EVENTS_FILE: _____, CI: ______, ...rest } = process.env;
  return { d, env: { ...rest, LAKE_SLOT_DIR: join(d, "slots"), FW_TIMINGS_FILE: join(d, "timings.jsonl"), LAKE_SLOT_CORES: "8" } };
};
const run = (env, cmd) => spawnSync("sh", [wrapper, "sh", "-c", cmd], { env, encoding: "utf8" });
const until = async (p, ms = 10000) => {
  const end = Date.now() + ms;
  while (!p()) {
    if (Date.now() > end) throw new Error("timed out");
    await new Promise((r) => setTimeout(r, 20));
  }
};
const hold = (env, d, name) => {
  const c = spawn("sh", [wrapper, "sh", "-c", `${probe} > "$1"; while [ ! -e "$2" ]; do sleep 0.05; done`, "_", join(d, `${name}.out`), join(d, `${name}.go`)], { env, stdio: "ignore" });
  const done = new Promise((r) => c.on("exit", (code) => r(code)));
  return { out: () => (existsSync(join(d, `${name}.out`)) ? readFileSync(join(d, `${name}.out`), "utf8").trim() : null), release: () => writeFileSync(join(d, `${name}.go`), ""), done };
};

test("the generated constants: a GENERATED first line, slot 0 full, slot 1 half of the dev Mac's 8, bound 12", () => {
  assert.match(genText.split("\n")[0], /^# GENERATED by Fw\.Sched\.LakeSlot\.gen/);
  assert.deepEqual(pools, ["full", "4"]);
  assert.equal(gen.LAKE_SLOT_BOUND, "12");
});

test("a solo build gets slot 0 and the caller's pool (LEAN_NUM_THREADS untouched)", () => {
  const { d, env } = scratch();
  try {
    assert.equal(run(env, probe).stdout.trim(), "0 unset");
    assert.equal(run({ ...env, LEAN_NUM_THREADS: "6" }, probe).stdout.trim(), "0 6");
  } finally { rmSync(d, { recursive: true, force: true }); }
});

