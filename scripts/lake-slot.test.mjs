// node --test scripts/lake-slot.test.mjs (task lake-build-slots): scripts/lake-slot.sh on a scratch slot directory.
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LINT_ARGV } from "../apps/runner/src/land-verdict.ts";

const top = join(dirname(fileURLToPath(import.meta.url)), "..");
const wrapper = join(top, "scripts/lake-slot.sh");
const genText = readFileSync(join(top, "packages/contracts/golden/sched/lake-slot.gen.sh"), "utf8");
const gen = Object.fromEntries(genText.split("\n").filter((l) => /^[A-Z_]+=/.test(l)).map((l) => {
  const [k, v] = l.split(/=(.*)/s);
  return [k, v.replace(/^'|'$/g, "")];
}));
const pools = gen.LAKE_SLOT_POOLS.split(" ");
const probe = 'echo "$LAKE_SLOT ${LEAN_NUM_THREADS-unset}"';

const scratch = () => {
  const d = mkdtempSync(join(tmpdir(), "lake-slot-test-"));
  const { LEAN_NUM_THREADS: _, LAKE_SLOT: __, ...rest } = process.env;
  return { d, env: { ...rest, LAKE_SLOT_DIR: join(d, "slots") } };
};
const run = (env, cmd) => spawnSync("sh", [wrapper, "sh", "-c", cmd], { env, encoding: "utf8" });
const until = async (p, ms = 10000) => {
  const end = Date.now() + ms;
  while (!p()) {
    if (Date.now() > end) throw new Error("timed out");
    await new Promise((r) => setTimeout(r, 20));
  }
};
const hold = (env, d, name) => {
  const c = spawn("sh", [wrapper, "sh", "-c", `${probe} > "$1"; while [ ! -e "$2" ]; do sleep 0.05; done`, "_", join(d, `${name}.out`), join(d, `${name}.go`)], { env, stdio: "ignore" });
  const done = new Promise((r) => c.on("exit", (code) => r(code)));
  return { out: () => (existsSync(join(d, `${name}.out`)) ? readFileSync(join(d, `${name}.out`), "utf8").trim() : null), release: () => writeFileSync(join(d, `${name}.go`), ""), done };
};

test("the generated constants: a GENERATED first line, slot 0 full, slot 1 half of the dev Mac's 8, bound 12", () => {
  assert.match(genText.split("\n")[0], /^# GENERATED by Fw\.Sched\.LakeSlot\.gen/);
  assert.deepEqual(pools, ["full", "4"]);
  assert.equal(gen.LAKE_SLOT_BOUND, "12");
});

test("a solo build gets slot 0 and the caller's pool (LEAN_NUM_THREADS untouched)", () => {
  const { d, env } = scratch();
  try {
    assert.equal(run(env, probe).stdout.trim(), "0 unset");
    assert.equal(run({ ...env, LEAN_NUM_THREADS: "6" }, probe).stdout.trim(), "0 6");
  } finally { rmSync(d, { recursive: true, force: true }); }
});

test("the command's exit status is returned, 75 included", () => {
  const { d, env } = scratch();
  try {
    assert.equal(run(env, "exit 3").status, 3);
    assert.equal(run(env, "exit 75").status, 75);
    assert.equal(run(env, "exit 0").status, 0);
  } finally { rmSync(d, { recursive: true, force: true }); }
});

test("re-entrancy: a nested call runs inside the caller's slot", () => {
  const { d, env } = scratch();
  try {
    const r = spawnSync("sh", [wrapper, "sh", wrapper, "sh", "-c", probe], { env, encoding: "utf8", timeout: 10000 });
    assert.equal(r.stdout.trim(), "0 unset");
    assert.equal(run({ ...env, LAKE_SLOT: "1" }, probe).stdout.trim(), "1 unset");
  } finally { rmSync(d, { recursive: true, force: true }); }
});

test("concurrent builds: the second gets slot 1 with the capped pool, a third waits until a slot frees", async () => {
  const { d, env } = scratch();
  try {
    const a = hold(env, d, "a");
    await until(() => a.out() !== null);
    assert.equal(a.out(), "0 unset");
    const second = run(env, probe);
    assert.equal(second.stdout.trim(), `1 ${pools[1]}`);
    assert.match(second.stderr, /lake-slot: slot 1, pool 4/);
    const b = hold(env, d, "b");
    await until(() => b.out() !== null);
    assert.equal(b.out(), `1 ${pools[1]}`);
    const c = hold(env, d, "c");
    await new Promise((r) => setTimeout(r, 1500));
    assert.equal(c.out(), null);
    a.release();
    assert.equal(await a.done, 0);
    await until(() => c.out() !== null);
    assert.equal(c.out(), "0 unset");
    b.release(); c.release();
    assert.equal(await b.done, 0);
    assert.equal(await c.done, 0);
  } finally { rmSync(d, { recursive: true, force: true }); }
});

test("the call sites build through the wrapper", () => {
  assert.match(readFileSync(join(top, "scripts/fwcore-build.sh"), "utf8"), /lake-slot\.sh lake build/);
  assert.match(readFileSync(join(top, "lean/scripts/check.sh"), "utf8"), /lake-slot\.sh sh \.\.\/scripts\/fwcore-build\.sh/);
  assert.match(LINT_ARGV.axioms.join(" "), /lake-slot\.sh lake build/);
});
