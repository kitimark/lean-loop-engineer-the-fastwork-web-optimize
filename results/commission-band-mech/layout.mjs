import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const rowsPath = path.join(here, 'layout-rows.json');
const leanPath = path.join(repo, 'lean/Fw/Parts/CommissionOptLayout.lean');

const dec = (v) => {
  const s = String(v);
  if (!/^-?\d+(\.\d{1,12})?$/.test(s)) throw new Error(`rect number not a plain decimal: ${s}`);
  return s;
};

export function extract(gate, runId) {
  const rows = [];
  for (const p of gate.probes) {
    const rw = p.rewrite.raw;
    const first = rw.viewFirst && rw.viewFirst.commission;
    if (!first) throw new Error(`probe ${p.id}: no first read of the commission part`);
    const sec = first.section.items[0].rect;
    const card = first.card.items[0].rect;
    rows.push({
      id: p.id,
      width: p.env.width,
      height: p.env.height,
      deviceWidth: p.env.deviceWidth,
      hover: p.env.hover,
      pointer: p.env.pointer,
      reducedMotion: p.env.reducedMotion,
      sectionTop: dec(sec.y),
      sectionH: dec(sec.h),
      cardTop: dec(card.y),
      cardH: dec(card.h),
    });
  }
  return { source: 'CI Chromium breakpoint-gate, rewrite arm, raw.viewFirst.commission (section, card)', run: String(runId), rows };
}

const ratLit = (s) => {
  const neg = s.startsWith('-');
  const [i, f = ''] = (neg ? s.slice(1) : s).split('.');
  return `(${neg ? '-' : ''}${i}${f} / 1${'0'.repeat(f.length)} : Rat)`;
};
const natOf = (v) => {
  const half = !Number.isInteger(v);
  return { n: Math.floor(v), half };
};

export function lean(doc) {
  const out = [];
  out.push(`-- GENERATED by node results/commission-band-mech/layout.mjs --write from results/commission-band-mech/layout-rows.json: do not edit by hand`);
  out.push(`import Fw.Site.Breakpoints`);
  out.push(``);
  out.push(`/-!`);
  out.push(`Commission section and card rects, read in CI Chromium at every breakpoint probe of the gate (run ${doc.run}):`);
  out.push(`the page at the top, so a rect's y is its document top. Task commission-band-mech.`);
  out.push(`-/`);
  out.push(`namespace Fw.Parts.CommissionOptLayout`);
  out.push(`open Fw.Site.Breakpoints`);
  out.push(``);
  out.push(`/-- One probe: viewport, input capabilities and the first read of the section and the card (px, document coordinates). -/`);
  out.push(`structure Row where`);
  out.push(`  id : String`);
  out.push(`  width : Nat`);
  out.push(`  widthHalf : Bool`);
  out.push(`  height : Nat`);
  out.push(`  deviceWidth : Nat -- the whole px of the probe device width (the gate probes .5 widths with a whole device width at the same edge)`);
  out.push(`  hover : Hover`);
  out.push(`  pointer : Pointer`);
  out.push(`  reduced : Bool`);
  out.push(`  sectionTop : Rat`);
  out.push(`  sectionH : Rat`);
  out.push(`  cardTop : Rat`);
  out.push(`  cardH : Rat`);
  out.push(``);
  out.push(`/-- The gate run the rects come from. -/`);
  out.push(`def sourceRun : String := ${JSON.stringify(doc.run)}`);
  out.push(``);
  out.push(`/-- The media environment of a probe. -/`);
  out.push(`def Row.env (r : Row) : Env :=`);
  out.push(`  { exEnv r.width r.deviceWidth r.hover r.pointer with`);
  out.push(`    width := if r.widthHalf then Px.half r.width else .ofNat r.width, height := .ofNat r.height }`);
  out.push(``);
  out.push(`/-- Every probe of the run, in the run's order. -/`);
  out.push(`def rows : List Row := [`);
  const rowsText = doc.rows.map((r) => {
    const w = natOf(r.width);
    const hover = r.hover === 'none' ? '.none' : '.hover';
    const pointer = r.pointer === 'coarse' ? '.coarse' : r.pointer === 'none' ? '.none' : '.fine';
    return `  ⟨${JSON.stringify(r.id)}, ${w.n}, ${w.half}, ${r.height}, ${Math.floor(r.deviceWidth)}, ${hover}, ${pointer}, ${r.reducedMotion === 'reduce'}, ${ratLit(r.sectionTop)}, ${ratLit(r.sectionH)}, ${ratLit(r.cardTop)}, ${ratLit(r.cardH)}⟩`;
  });
  out.push(rowsText.join(',\n'));
  out.push(`]`);
  out.push(``);
  out.push(`end Fw.Parts.CommissionOptLayout`);
  return out.join('\n') + '\n';
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const [mode, a, b] = process.argv.slice(2);
  if (mode === '--extract') {
    const doc = extract(JSON.parse(fs.readFileSync(a, 'utf8')), b);
    fs.writeFileSync(rowsPath, JSON.stringify(doc, null, 1) + '\n');
    process.stderr.write(`layout: ${doc.rows.length} rows from run ${doc.run}\n`);
  } else if (mode === '--write') {
    fs.writeFileSync(leanPath, lean(JSON.parse(fs.readFileSync(rowsPath, 'utf8'))));
    process.stderr.write(`layout: wrote ${path.relative(repo, leanPath)}\n`);
  } else if (mode === '--check') {
    const want = lean(JSON.parse(fs.readFileSync(rowsPath, 'utf8')));
    if (fs.readFileSync(leanPath, 'utf8') !== want) {
      process.stderr.write(`layout: ${path.relative(repo, leanPath)} differs from the generation (run --write)\n`);
      process.exit(1);
    }
    process.stderr.write('layout: ok\n');
  } else {
    process.stderr.write('usage: layout.mjs --extract <gate chromium.json> <run id> | --write | --check\n');
    process.exit(2);
  }
}
