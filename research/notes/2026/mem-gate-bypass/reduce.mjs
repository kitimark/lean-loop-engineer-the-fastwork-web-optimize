// Reduces the node-resources sampler log (samples.jsonl, uncommitted: its ps rows hold home paths and session ids) into
// numbers.md, the one source of every sample-derived number in research/notes/2026/10-21-mem-gate-bypass.md.
// Usage: node reduce.mjs <samples.jsonl> > numbers.md
// A one-off JS reduction of uncommitted data: a stand-in, not a Lean decision (named in the note's accepted limits).
// It prints pids, sample indices, counts and sizes only; process args and cwds select rows but are never printed.
import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) { console.error("usage: node reduce.mjs <samples.jsonl>"); process.exit(2); }
const S = readFileSync(file, "utf8").trim().split("\n").map((l) => JSON.parse(l));

const LEAN = new Set(["lean", "lake", "propslint", "fwcore"]);
const OFFSET_S = 7 * 3600; // the sampler host's UTC offset, so the times read as the note's local times
const argv = (p) => (p.cmd ?? "").split(" ");
/** argv0 basename; null for a parenthesised (exiting) row such as `(lean)`. */
const base = (p) => { const t = argv(p)[0]; return t.startsWith("(") ? null : t.split("/").pop(); };
const isLean = (p) => LEAN.has(base(p));
const mib = (kb) => Math.round(kb / 1024);
const gib = (kb) => (kb / 1024 / 1024).toFixed(2);
const gb1 = (mb) => (Math.abs(mb) / 1024).toFixed(1);
const hms = (ts) => new Date((ts + OFFSET_S) * 1000).toISOString().slice(11, 19);
const sum = (ps) => ps.reduce((a, p) => a + p.rss_kb, 0);
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); const m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
const swapOf = (s) => { const m = /total = ([\d.]+)M\s+used = ([\d.]+)M/.exec(s.swap); return { used: Number(m[2]), total: Number(m[1]) }; };
const pct = (s) => { const w = swapOf(s); return (100 * w.used / w.total).toFixed(1); };
/** Location class of a cwd; only the class is printed. */
const where = (p) => {
  const c = p.cwd ?? "";
  const lw = /\/\.claude\/land-wt\/(\d+)(\/|$)/.exec(c);
  if (lw) return `land-wt/${lw[1]}`;
  if (c.includes("/.claude/worktrees/")) return "agent worktree";
  return c ? "main checkout" : "unknown";
};
const byPid = (s) => new Map(s.procs.map((p) => [p.pid, p]));
/** A process and all its descendants in one sample. */
const tree = (s, root) => {
  const kids = new Map();
  for (const p of s.procs) { if (!kids.has(p.ppid)) kids.set(p.ppid, []); kids.get(p.ppid).push(p); }
  const out = []; const st = [root];
  while (st.length) { const p = st.pop(); out.push(p); for (const k of kids.get(p.pid) ?? []) st.push(k); }
  return out;
};
const ancestors = (s, p) => { const m = byPid(s); const out = []; let q = m.get(p.ppid); while (q && !out.includes(q)) { out.push(q); q = m.get(q.ppid); } return out; };
const range = (xs, f) => { const lo = Math.min(...xs), hi = Math.max(...xs); return lo === hi ? f(lo) : `${f(lo)}-${f(hi)}`; };

const out = [];
const w = (l = "") => out.push(l);

w("# mem-gate-bypass: numbers from samples.jsonl");
w();
w("Generated by `node research/notes/2026/mem-gate-bypass/reduce.mjs <samples.jsonl>`; do not edit by hand. Rules:");
w();
w("- Lean process: argv0 basename exactly `lean`, `lake`, `propslint` or `fwcore`; parenthesised (exiting) rows such as `(lean)` are excluded.");
w("- Lean RSS: sum of ps RSS (KB) over the Lean processes of one sample. MiB = KB/1024 rounded to the nearest integer (sums are");
w("  rounded once, after summing); GiB = KB/1024/1024 to two decimals.");
w("- Tree: a process and all its descendants by ppid in the same sample.");
w("- VM counters are the sampler's `vm_stat` pages x page size / 2^20, labelled MB as the sampler does; GB = MB/1024 to one decimal.");
w("- Time: sample `ts` at UTC+07:00 (the sampler host's local time).");
w("- Burst: a sample whose Lean RSS is at least 4096 MiB; its \"before\" sample is the previous index.");
w("- Heavy-lock process: args contain `scripts/heavy-lock.mjs run`. Inner check.sh: its child with args `sh scripts/check.sh`.");
w("  Outer root: walk up from the heavy-lock process while the parent's argv0 basename is `zsh` (the Bash tool's shell).");
w("- Jobs of a check.sh tree: its processes with argv0 basename `lean` or `propslint`.");
w("- fwcore-build tree: rooted at a process with args `sh scripts/fwcore-build.sh` or `sh ../scripts/fwcore-build.sh`.");
w("- Location class from the cwd: `land-wt/<n>` (below `.claude/land-wt/<n>`), `agent worktree` (below `.claude/worktrees/`),");
w("  else `main checkout`; only the class is printed.");
w("- Agent build: a `lake build` process whose every ancestor in the sample has argv0 basename `zsh`, `timeout` or `claude`.");
w("- Axiom check: tree rooted at a process whose args contain `axiom-check.sh`. Lake serve: tree rooted at `lake serve`.");
w("- Serena Lean: the process with argv0 basename `uv` whose args contain `serena start-mcp-server` and `--project lean`; its parent must have argv0");
w("  basename `claude` (the reducer exits non-zero otherwise).");
w("- Output holds pids, sample indices, counts and sizes only: no cwd and no args.");
w();

// Window
const free = S.map((s) => s.vm.free_mb);
const minFree = Math.min(...free), maxFree = Math.max(...free);
const swp = S.map((s) => Number(pct(s)));
w("## Window");
w();
w("| Item | Value |");
w("|---|---|");
w(`| samples | ${S.length}, i=${S[0].i}..${S.at(-1).i}, ${hms(S[0].ts)}-${hms(S.at(-1).ts)}, step ${range(S.slice(1).map((s, k) => s.ts - S[k].ts), String)} s |`);
w(`| free MB min | ${minFree} (i=${S.filter((s) => s.vm.free_mb === minFree).map((s) => s.i).join(",")}) |`);
w(`| free MB max | ${maxFree} (i=${S.filter((s) => s.vm.free_mb === maxFree).map((s) => s.i).join(",")}) |`);
w(`| free MB median | ${median(free)} |`);
w(`| free MB range | ${minFree}-${maxFree} MB |`);
w(`| samples with free <= 330 MB | ${free.filter((f) => f <= 330).length} of ${S.length} |`);
w(`| swap total | ${range(S.map((s) => swapOf(s).total), (x) => x.toFixed(0))} MB |`);
w(`| swap used | ${range(S.map((s) => swapOf(s).used), (x) => x.toFixed(2))} MB, ${Math.min(...swp).toFixed(1)}-${Math.max(...swp).toFixed(1)}% |`);
const runs = []; for (const s of S) { const last = runs.at(-1); if (last && last.p === s.pressure) last.hi = s.i; else runs.push({ p: s.pressure, lo: s.i, hi: s.i }); }
w(`| pressure runs | ${runs.map((r) => `${r.p} at i=${r.lo}-${r.hi}`).join("; ")} |`);
const so = S.slice(1).map((s, k) => ({ i: s.i, prev: S[k].i, d: s.vm.swapouts - S[k].vm.swapouts })).filter((x) => x.d !== 0);
w(`| swap-out changes | ${so.map((x) => `i=${x.prev} to i=${x.i}: +${x.d}`).join("; ") || "none"}; flat from i=${(so.at(-1)?.i ?? 0)} to i=${S.at(-1).i} |`);
w();

// Per sample
w("## Per sample");
w();
w("| i | Time | Lean RSS MiB | Lean procs | Heavy-lock pids | Free MB | Swap used MB (%) | Pressure | Load 1 min |");
w("|---|---|---|---|---|---|---|---|---|");
const heavy = (s) => s.procs.filter((p) => (p.cmd ?? "").includes("scripts/heavy-lock.mjs run"));
for (const s of S) {
  const lp = s.procs.filter(isLean);
  w(`| ${s.i} | ${hms(s.ts)} | ${mib(sum(lp))} | ${lp.length} | ${heavy(s).map((p) => p.pid).join(", ") || "-"} | ${s.vm.free_mb} | ${swapOf(s).used.toFixed(2)} (${pct(s)}%) | ${s.pressure} | ${s.load[0].toFixed(2)} |`);
}
w();

// Bursts
const bursts = S.filter((s) => mib(sum(s.procs.filter(isLean))) >= 4096);
const B = bursts.map((s) => {
  const hl = heavy(s);
  if (hl.length !== 1) { console.error(`i=${s.i}: ${hl.length} heavy-lock processes`); process.exit(1); }
  const h = hl[0];
  const inner = s.procs.find((p) => p.ppid === h.pid && p.cmd === "sh scripts/check.sh");
  const t = tree(s, inner);
  const jobs = t.filter((p) => ["lean", "propslint"].includes(base(p)));
  const m = byPid(s); let outer = h; while (m.get(outer.ppid) && base(m.get(outer.ppid)) === "zsh") outer = m.get(outer.ppid);
  const ot = tree(s, outer);
  const lp = s.procs.filter(isLean);
  return { s, h, inner, t, jobs, outer, ot, lp, prev: S[S.indexOf(s) - 1] };
});
w("## Bursts");
w();
w("| Burst | Time | Lean RSS | Heavy-lock pid (count) | Inner check.sh pid | Its tree | Jobs lean + propslint | Jobs RSS | Outer root pid | Outer tree | Outer minus inner | Heavy-lock node RSS |");
w("|---|---|---|---|---|---|---|---|---|---|---|---|");
for (const b of B) {
  const nl = b.jobs.filter((p) => base(p) === "lean").length, np = b.jobs.length - nl;
  w(`| i=${b.s.i} | ${hms(b.s.ts)} | ${mib(sum(b.lp))} MiB (${gib(sum(b.lp))} GiB), ${b.lp.length} procs | ${b.h.pid} (${heavy(b.s).length}) | ${b.inner.pid} | ${mib(sum(b.t))} MiB (${gib(sum(b.t))} GiB), ${b.t.length} procs | ${nl} + ${np} | ${mib(sum(b.jobs))} MiB | ${b.outer.pid} | ${mib(sum(b.ot))} MiB, ${b.ot.length} procs | ${mib(sum(b.ot)) - mib(sum(b.t))} MiB | ${mib(b.h.rss_kb)} MiB |`);
}
w();
w("Ranges over the bursts:");
w();
w("| Measure | Range |");
w("|---|---|");
w(`| Lean RSS | ${range(B.map((b) => mib(sum(b.lp))), String)} MiB = ${gib(Math.min(...B.map((b) => sum(b.lp))))}-${gib(Math.max(...B.map((b) => sum(b.lp))))} GiB = ${(Math.min(...B.map((b) => sum(b.lp))) / 1048576).toFixed(1)}-${(Math.max(...B.map((b) => sum(b.lp))) / 1048576).toFixed(1)} GiB |`);
w(`| inner check.sh tree | ${range(B.map((b) => mib(sum(b.t))), String)} MiB = ${gib(Math.min(...B.map((b) => sum(b.t))))}-${gib(Math.max(...B.map((b) => sum(b.t))))} GiB |`);
w(`| outer minus inner | ${range(B.map((b) => mib(sum(b.ot)) - mib(sum(b.t))), String)} MiB |`);
w(`| heavy-lock node RSS | ${range(B.map((b) => mib(b.h.rss_kb)), String)} MiB |`);
w();

// VM counters
const vmRows = [
  ["Compressor (MB)", (s) => s.vm.compressed_mb],
  ["Wired (MB)", (s) => s.vm.wired_mb],
  ["Compressor + wired (MB)", (s) => s.vm.compressed_mb + s.vm.wired_mb],
  ["Active + inactive (MB)", (s) => s.vm.active_mb + s.vm.inactive_mb],
  ["Free (MB)", (s) => s.vm.free_mb],
  ["Swap-outs (cumulative)", (s) => s.vm.swapouts],
];
w("## VM counters per burst (before sample to burst sample)");
w();
w(`| Counter | ${B.map((b) => `i=${b.prev.i} -> i=${b.s.i}`).join(" | ")} |`);
w(`|---|${B.map(() => "---").join("|")}|`);
const sg = (d) => (d >= 0 ? `+${d}` : `${d}`);
for (const [name, f] of vmRows) w(`| ${name} | ${B.map((b) => `${f(b.prev)} -> ${f(b.s)} (${sg(f(b.s) - f(b.prev))})`).join(" | ")} |`);
w(`| Swap used MB (%) | ${B.map((b) => `${swapOf(b.prev).used.toFixed(2)} (${pct(b.prev)}%) -> ${swapOf(b.s).used.toFixed(2)} (${pct(b.s)}%)`).join(" | ")} |`);
w(`| Pressure level | ${B.map((b) => `${b.prev.pressure} -> ${b.s.pressure}`).join(" | ")} |`);
w(`| Load, 1 min | ${B.map((b) => `${b.prev.load[0].toFixed(2)} -> ${b.s.load[0].toFixed(2)}`).join(" | ")} |`);
w();
const dRange = (f, label) => { const ds = B.map((b) => f(b.s) - f(b.prev)); return `| ${label} | ${ds.map(sg).join(", ")} MB | ${gb1(Math.min(...ds.map(Math.abs)))}-${gb1(Math.max(...ds.map(Math.abs)))} GB |`; };
w("| Change per burst | Values | Range |");
w("|---|---|---|");
w(dRange((s) => s.vm.compressed_mb, "compressor grew"));
w(dRange((s) => s.vm.wired_mb, "wired grew"));
w(dRange((s) => s.vm.compressed_mb + s.vm.wired_mb, "compressor + wired grew"));
w(dRange((s) => s.vm.active_mb + s.vm.inactive_mb, "active + inactive fell"));
w();

// fwcore-build trees
w("## fwcore-build trees");
w();
w("| i | Root pid | Location | Tree MiB | Procs | `lean` procs |");
w("|---|---|---|---|---|---|");
for (const s of S) for (const p of s.procs.filter((q) => q.cmd === "sh scripts/fwcore-build.sh" || q.cmd === "sh ../scripts/fwcore-build.sh")) {
  const t = tree(s, p);
  w(`| ${s.i} | ${p.pid} | ${where(p)} | ${mib(sum(t))} | ${t.length} | ${t.filter((q) => base(q) === "lean").length} |`);
}
w();

// Other trees: peaks over the window
const peaks = (sel) => {
  const by = new Map();
  for (const s of S) for (const p of s.procs.filter((q) => sel(s, q))) {
    const kb = sum(tree(s, p)); const cur = by.get(p.pid);
    if (!cur) by.set(p.pid, { pid: p.pid, first: s.i, last: s.i, kb, at: s.i, where: where(p) });
    else { cur.last = s.i; if (kb > cur.kb) { cur.kb = kb; cur.at = s.i; } }
  }
  return [...by.values()];
};
const agentBuild = (s, p) => base(p) === "lake" && argv(p)[1] === "build" && ancestors(s, p).every((q) => ["zsh", "timeout", "claude"].includes(base(q)));
w("## Other trees: peak over the window");
w();
w("| Tree | Root pid | Location | Present i | Peak tree MiB | At |");
w("|---|---|---|---|---|---|");
const kinds = [
  ["agent `lake build`", agentBuild],
  ["axiom check", (s, p) => (p.cmd ?? "").includes("axiom-check.sh") && !ancestors(s, p).some((q) => (q.cmd ?? "").includes("axiom-check.sh"))],
  ["`lake serve`", (s, p) => base(p) === "lake" && argv(p)[1] === "serve"],
];
for (const [name, sel] of kinds) for (const r of peaks(sel)) w(`| ${name} | ${r.pid} | ${r.where} | ${r.first}-${r.last} | ${mib(r.kb)} | i=${r.at} |`);
w();

// Beside each burst
w("## Lean processes outside the check.sh tree at each burst");
w();
w("| Burst | Pid | Ppid | argv0 basename | RSS MiB | Location |");
w("|---|---|---|---|---|---|");
const outsidePids = new Set();
for (const b of B) {
  const inT = new Set(b.t.map((p) => p.pid));
  for (const p of b.lp.filter((q) => !inT.has(q.pid)).sort((x, y) => x.pid - y.pid)) {
    outsidePids.add(p.pid);
    w(`| i=${b.s.i} | ${p.pid} | ${p.ppid} | ${base(p)} | ${mib(p.rss_kb)} | ${where(p)} |`);
  }
}
w();
w("Lifetime of those pids in the window:");
w();
w("| Pid | Present i | etime at last present sample (s) |");
w("|---|---|---|");
for (const pid of [...outsidePids].sort((a, b) => a - b)) {
  const here = S.filter((s) => s.procs.some((p) => p.pid === pid));
  const last = here.at(-1).procs.find((p) => p.pid === pid);
  w(`| ${pid} | ${here[0].i}-${here.at(-1).i}${here.length === here.at(-1).i - here[0].i + 1 ? "" : ` (${here.length} samples)`} | ${last.etime_s} |`);
}
w();
w("`lake serve` trees at each burst:");
w();
w("| Burst | Root pid | Tree pids | Tree MiB |");
w("|---|---|---|---|");
for (const b of B) for (const p of b.s.procs.filter((q) => base(q) === "lake" && argv(q)[1] === "serve")) {
  const t = tree(b.s, p);
  w(`| i=${b.s.i} | ${p.pid} | ${t.map((q) => q.pid).sort((x, y) => x - y).join(", ")} | ${mib(sum(t))} |`);
}
w();
w("Console `fwcore` children (argv0 basename `fwcore`, parent argv0 basename `node`) at each burst:");
w();
w("| Burst | Pid | RSS MiB |");
w("|---|---|---|");
const fwcRss = [];
for (const b of B) { const m = byPid(b.s); for (const p of b.lp.filter((q) => base(q) === "fwcore" && base(m.get(q.ppid) ?? {}) === "node")) { fwcRss.push(p.rss_kb); w(`| i=${b.s.i} | ${p.pid} | ${mib(p.rss_kb)} (${p.rss_kb} KB) |`); } }
w();
w(`Range: ${range(fwcRss.map(mib), String)} MiB.`);
w();

// Serena Lean
w("## Serena Lean server");
w();
w("| Burst | uv pid | Its ppid | Parent etime (s) | Tree pids | Tree MiB | `lean` pid in tree | Its RSS KB |");
w("|---|---|---|---|---|---|---|---|");
for (const b of B) {
  const m = byPid(b.s);
  for (const p of b.s.procs.filter((q) => base(q) === "uv" && (q.cmd ?? "").includes("serena start-mcp-server") && / --project lean( |$)/.test(q.cmd))) {
    const par = m.get(p.ppid);
    if (!par || base(par) !== "claude") { console.error(`i=${b.s.i}: serena-lean parent is not claude`); process.exit(1); }
    const t = tree(b.s, p); const ln = t.filter((q) => base(q) === "lean");
    w(`| i=${b.s.i} | ${p.pid} | ${p.ppid} | ${par.etime_s} | ${t.map((q) => q.pid).sort((x, y) => x - y).join(", ")} | ${mib(sum(t))} | ${ln.map((q) => q.pid).join(", ")} | ${ln.map((q) => q.rss_kb).join(", ")} |`);
  }
}

process.stdout.write(out.join("\n") + "\n");
