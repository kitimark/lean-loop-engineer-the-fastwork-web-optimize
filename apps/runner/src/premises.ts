// `fw premises [--results <dir|file>...] [--golden <premise.jsonl>] [--json]`: the empirical premises of the Lean theorems
// against the browser tests (packages/premise-tests). The registry is Lean (lean/Fw/Ops/Premise.lean); this file only reads
// its golden rows, ports its pure checks (TS stand-ins, checked against the golden lint, flag, ack, ackcase, acklint and
// errorclass rows in test/premises.test.ts) and prints. A failing premise test is a finding: the theorems that assume
// it are listed. A finding acknowledged in Lean (`Fw.Ops.Premise.acks`, citing its research/findings/ledger.json id) is
// printed separately and does not fail; a new or changed finding, or a stale acknowledgement, fails (`red_iff_unacked`).
//
//   no --results   static lint: the tests the package declares (src/tests.mjs) against the registry's page premises,
//                  the registry's lane premises against the files in .github/workflows (a lane premise's testId is the
//                  workflow that asserts it), a check that every theorem a premise names is a declaration in
//                  lean/Fw (names starting `planned:` are tasks), and the ack lint (premise and ledger id exist)
//   --results      the JSON files of `node packages/premise-tests/src/run.mjs` (a directory is searched recursively),
//                  one per engine: lint on the tests they declare, then the ack verdict on the observed findings
//                  (lane premises have no page results; their workflow asserts them)
//   exit codes     0 clean, 3 lint findings, unacknowledged findings, stale acks or an unknown theorem name, 64 usage
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { UsageError } from "./lib.ts";

export const PREMISES_USAGE =
  "usage: fw premises [--results <dir|file>]... [--golden <premise.jsonl>] [--json]\n" +
  "  without --results: static lint of the declared tests against the Lean registry and of the theorem names";

export type Engine = "chromium" | "webkit";
export type TestKind = "page" | "lane";
export type Premise = { id: string; statement: string; theorems: string[]; engines: Engine[]; testId: string; testKind: TestKind };
export type TestRef = { id: string; premise: string };
export type Result = { testId: string; engine: Engine; ok: boolean; error?: string };
export type Lint = { untested: string[]; unknown: string[] };
export type LintCase = { name: string; tests: TestRef[]; files: string[]; untested: string[]; unknown: string[] };
export type FlagCase = { name: string; results: Result[]; flagged: { premise: string; theorems: string[] }[] };
/** Lean `Observed`: a premise that does not hold on an engine, with the observed class (`cls` in Lean). */
export type Observed = { premise: string; engine: Engine; class: string };
/** Lean `Ack`: an acknowledged finding, citing its `research/findings/ledger.json` id. */
export type Ack = Observed & { finding: string; intermittent: boolean };
export type AckVerdict = { acked: Observed[]; unacked: Observed[]; stale: Ack[] };
export type AckCase = { name: string; results: Result[]; findings: Observed[] } & AckVerdict & { red: boolean };
export type AckLintCase = { name: string; ids: string[]; acks: Ack[]; bad: Ack[] };
export type ErrorClassCase = { error: string; class: string };
export type Golden = {
  premises: Premise[]; lint: LintCase[]; flag: FlagCase[];
  acks: Ack[]; ackCases: AckCase[]; ackLint: AckLintCase[]; errorClass: ErrorClassCase[];
};

/** Parse `packages/contracts/golden/ops/premise.jsonl` (generated by `lake env lean --run scripts/PremiseGolden.lean`). */
export function parseGolden(text: string): Golden {
  const g: Golden = { premises: [], lint: [], flag: [], acks: [], ackCases: [], ackLint: [], errorClass: [] };
  text.split("\n").forEach((line, i) => {
    if (!line.trim()) return;
    let row: Record<string, unknown>;
    try { row = JSON.parse(line) as Record<string, unknown>; } catch { throw new Error(`premise golden line ${i + 1}: not JSON`); }
    if (row.kind === "premise") g.premises.push(row as unknown as Premise);
    else if (row.kind === "lint") g.lint.push(row as unknown as LintCase);
    else if (row.kind === "flag") g.flag.push(row as unknown as FlagCase);
    else if (row.kind === "ack") {
      const { kind: _k, ...a } = row;
      g.acks.push(a as unknown as Ack);
    } else if (row.kind === "ackcase") g.ackCases.push(row as unknown as AckCase);
    else if (row.kind === "acklint") g.ackLint.push(row as unknown as AckLintCase);
    else if (row.kind === "errorclass") g.errorClass.push(row as unknown as ErrorClassCase);
    else throw new Error(`premise golden line ${i + 1}: unknown kind`);
  });
  return g;
}

/** `covered` (Lean): a page premise has a declared test naming it; a lane premise's workflow file exists. */
export function covered(ts: TestRef[], files: string[], p: Premise): boolean {
  return p.testKind === "lane" ? files.includes(p.testId) : ts.some((t) => t.id === p.testId && t.premise === p.id);
}

/** `premiseLint` (Lean: Fw.Ops.Premise.premiseLint): premises without a test (lane: without its workflow file among
 * `files`), tests naming no registered page premise. */
export function premiseLint(ps: Premise[], ts: TestRef[], files: string[]): Lint {
  return {
    untested: ps.filter((p) => !covered(ts, files, p)).map((p) => p.id),
    unknown: ts.filter((t) => !ps.some((p) => p.testKind === "page" && p.id === t.premise && p.testId === t.id)).map((t) => t.id),
  };
}

/** `holds` (Lean): the test ran on the engine at least once and every run passed. */
export function holds(rs: Result[], p: Premise, e: Engine): boolean {
  const m = rs.filter((r) => r.testId === p.testId && r.engine === e);
  return m.length > 0 && m.every((r) => r.ok);
}

/** `flagged` (Lean: Fw.Ops.Premise.flagged): page premises that do not hold on some engine they need (failed or missing). */
export function flagged(ps: Premise[], rs: Result[]): Premise[] {
  return ps.filter((p) => p.testKind === "page" && !p.engines.every((e) => holds(rs, p, e)));
}

// ---- acknowledged findings (Lean: Fw.Ops.Premise, section "Acknowledged findings"; TS stand-ins checked against the
// golden ack, ackcase, acklint and errorclass rows) ---------------------------------------------------------------

/** `errorClass` (Lean): the first line holding a character other than space, tab, CR, LF; else `failed`. */
export function errorClass(s: string): string {
  return s.split("\n").find((l) => /[^ \t\r\n]/.test(l)) ?? "failed";
}

/** `failClass` (Lean): `no result` without a run on `e`, else the error class of the first failing run, else `passed`. */
export function failClass(rs: Result[], p: Premise, e: Engine): string {
  const m = rs.filter((r) => r.testId === p.testId && r.engine === e);
  if (m.length === 0) return "no result";
  const bad = m.find((r) => !r.ok);
  return bad ? errorClass(bad.error ?? "") : "passed";
}

/** `findings` (Lean): per flagged premise and per needed engine it does not hold on, the observed class. */
export function findings(ps: Premise[], rs: Result[]): Observed[] {
  return flagged(ps, rs).flatMap((p) => p.engines.filter((e) => !holds(rs, p, e))
    .map((engine) => ({ premise: p.id, engine, class: failClass(rs, p, engine) })));
}

const sameObs = (a: Observed, f: Observed) => a.premise === f.premise && a.engine === f.engine && a.class === f.class;

/** `acked` (Lean): some acknowledgement accepts exactly this finding. */
export function acked(ks: Ack[], f: Observed): boolean { return ks.some((a) => sameObs(a, f)); }

/** `ackVerdict` (Lean): acknowledged findings, unacknowledged findings, stale (non-intermittent, unmatched) acks. */
export function ackVerdict(ks: Ack[], fs: Observed[]): AckVerdict {
  return {
    acked: fs.filter((f) => acked(ks, f)),
    unacked: fs.filter((f) => !acked(ks, f)),
    stale: ks.filter((a) => !a.intermittent && !fs.some((f) => sameObs(a, f))),
  };
}

/** `AckVerdict.red` (Lean). */
export function ackRed(v: AckVerdict): boolean { return v.unacked.length > 0 || v.stale.length > 0; }

/** `ackLint` (Lean): acks whose premise is no registered page premise or whose ledger id is not among `ids`. */
export function ackLint(ps: Premise[], ids: string[], ks: Ack[]): Ack[] {
  return ks.filter((a) => !ps.some((p) => p.testKind === "page" && p.id === a.premise) || !ids.includes(a.finding));
}

/** The `id`s of the entries of `research/findings/ledger.json` (glue: a missing or unreadable file gives none). */
export function ledgerIds(root: string): string[] {
  try {
    const l = JSON.parse(readFileSync(join(root, "research", "findings", "ledger.json"), "utf8")) as { findings?: { id?: unknown }[] };
    return (l.findings ?? []).flatMap((f) => (typeof f.id === "string" ? [f.id] : []));
  } catch { return []; }
}

// ---- files --------------------------------------------------------------------------------------------------------

export type ResultFile = { engine: Engine; browser?: string; tests: TestRef[]; results: (Result & { error?: string })[] };

function jsonFiles(path: string): string[] {
  if (!existsSync(path)) throw new UsageError(`no such path: ${path}`);
  if (statSync(path).isFile()) return [path];
  return readdirSync(path, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? jsonFiles(join(path, d.name)) : d.name.endsWith(".json") ? [join(path, d.name)] : []);
}

/** Read the per-engine result files under the given paths (files that are not premise results are skipped). */
export function readResults(paths: string[]): ResultFile[] {
  const out: ResultFile[] = [];
  for (const f of paths.flatMap(jsonFiles)) {
    let j: Partial<ResultFile> & { schema?: number };
    try { j = JSON.parse(readFileSync(f, "utf8")) as typeof j; } catch { continue; }
    if (j.schema !== 1 || !Array.isArray(j.tests) || !Array.isArray(j.results) || (j.engine !== "chromium" && j.engine !== "webkit")) continue;
    out.push(j as ResultFile);
  }
  return out;
}

/** The root of the checkout: the nearest parent holding the golden file. */
export function findRoot(cwd: string): string {
  let d = resolve(cwd);
  for (;;) {
    if (existsSync(join(d, "packages", "contracts", "golden", "ops", "premise.jsonl"))) return d;
    const up = dirname(d);
    if (up === d) throw new UsageError(`not inside the repo (no packages/contracts/golden/ops/premise.jsonl above ${cwd})`);
    d = up;
  }
}

/** The workflow files of the checkout, as repo-relative paths (`.github/workflows/<name>`). */
export function workflowFiles(root: string): string[] {
  const dir = join(root, ".github", "workflows");
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((n) => n.endsWith(".yml") || n.endsWith(".yaml")).map((n) => `.github/workflows/${n}`);
}

/** Declared names in lean/Fw (theorem, def, structure, ...), last name component. */
export function leanDeclared(root: string): Set<string> {
  const names = new Set<string>();
  const walk = (dir: string) => {
    for (const d of readdirSync(dir, { withFileTypes: true })) {
      if (d.isDirectory()) walk(join(dir, d.name));
      else if (d.name.endsWith(".lean")) {
        for (const m of readFileSync(join(dir, d.name), "utf8").matchAll(/^\s*(?:private\s+|protected\s+|noncomputable\s+)*(?:theorem|lemma|def|abbrev|structure|inductive|class|instance)\s+([^\s:({\[]+)/gm)) {
          const n = m[1]!; names.add(n.split(".").pop()!);
        }
      }
    }
  };
  walk(join(root, "lean", "Fw"));
  return names;
}

/** Theorem names of the registry that are neither `planned:` nor declared in lean/Fw. */
export function unknownTheorems(ps: Premise[], declared: Set<string>): { premise: string; theorem: string }[] {
  return ps.flatMap((p) => p.theorems
    .filter((t) => !t.startsWith("planned:") && !declared.has(t.split(".").pop()!))
    .map((theorem) => ({ premise: p.id, theorem })));
}

// ---- report -------------------------------------------------------------------------------------------------------

export type Report = {
  registered: number; lanes: number; tested: number; holding: number;
  lint: Lint; unknownTheorems: { premise: string; theorem: string }[];
  /** Unacknowledged findings (new premise, new engine or changed observation), grouped per premise: these fail. */
  flagged: { premise: string; engines: Engine[]; reason: string; theorems: string[] }[];
  /** Findings an acknowledgement accepts (Lean `acks`): printed, not failing. */
  acknowledged: (Ack & { theorems: string[] })[];
  /** Non-intermittent acknowledgements whose finding was not observed: remove them; these fail. */
  staleAcks: Ack[];
  /** Acknowledgements naming no registered page premise or no `research/findings/ledger.json` id: these fail. */
  ackLint: Ack[];
  ranEngines: Engine[]; ok: boolean;
};

/** Build the report: lint on the declared tests and workflow files, theorem-name check, ack lint against the ledger
 * ids (when given), and, when results are given, the ack verdict on the observed findings (Lean `ackVerdict` over
 * `findings`). */
export function report(g: Golden, tests: TestRef[], files: string[], results: Result[] | null, declared: Set<string> | null, ran: Engine[], ledger: string[] | null = null): Report {
  const lint = premiseLint(g.premises, tests, files);
  const pages = g.premises.filter((p) => p.testKind === "page").length;
  const unknown = declared ? unknownTheorems(g.premises, declared) : [];
  const fl = results ? flagged(g.premises, results) : [];
  const v = results ? ackVerdict(g.acks, findings(g.premises, results)) : { acked: [], unacked: [], stale: [] };
  const theoremsOf = (id: string) => g.premises.find((p) => p.id === id)?.theorems ?? [];
  const flaggedOut = [...new Set(v.unacked.map((f) => f.premise))].map((premise) => {
    const fs = v.unacked.filter((f) => f.premise === premise);
    const reason = fs.map((f) => {
      const was = g.acks.filter((a) => a.premise === f.premise && a.engine === f.engine).map((a) => a.class);
      return `${f.engine}: ${f.class}${was.length ? ` (changed; acknowledged: ${was.join(" | ")})` : ""}`;
    }).join("; ");
    return { premise, engines: fs.map((f) => f.engine), reason, theorems: theoremsOf(premise) };
  });
  const acknowledged = g.acks.filter((a) => v.acked.some((f) => f.premise === a.premise && f.engine === a.engine && f.class === a.class))
    .map((a) => ({ ...a, theorems: theoremsOf(a.premise) }));
  const ackBad = ledger ? ackLint(g.premises, ledger, g.acks) : [];
  const tested = g.premises.length - lint.untested.length;
  const ok = lint.untested.length === 0 && lint.unknown.length === 0 && unknown.length === 0 && !ackRed(v) && ackBad.length === 0;
  return {
    registered: g.premises.length, lanes: g.premises.length - pages, tested, holding: results ? pages - fl.length : 0, lint,
    unknownTheorems: unknown, flagged: flaggedOut, acknowledged, staleAcks: v.stale, ackLint: ackBad, ranEngines: ran, ok,
  };
}

export function render(r: Report, withResults: boolean): string {
  const lines: string[] = [];
  lines.push(`premises: ${r.registered} registered (${r.lanes} lane), ${r.tested} with a test${withResults ? `, ${r.holding} page premises hold on ${r.ranEngines.join(" + ") || "no engine"}` : ""}`);
  for (const id of r.lint.untested) lines.push(`LINT premise ${id} has no test`);
  for (const id of r.lint.unknown) lines.push(`LINT test ${id} names no registered premise`);
  for (const u of r.unknownTheorems) lines.push(`LINT premise ${u.premise}: theorem ${u.theorem} is not declared in lean/Fw`);
  for (const a of r.ackLint) lines.push(`LINT ack ${a.premise} on ${a.engine} cites ${a.finding}: no registered page premise or no such id in research/findings/ledger.json`);
  for (const f of r.flagged) {
    lines.push(`FINDING premise ${f.premise} does not hold (${f.reason})`);
    lines.push(`  theorems that assume it, no longer proved for this engine: ${f.theorems.join(", ")}`);
  }
  for (const a of r.staleAcks) lines.push(`STALE ack ${a.premise} on ${a.engine} (${a.finding}): "${a.class}" was not observed; remove it from Fw.Ops.Premise.acks`);
  if (r.acknowledged.length) {
    lines.push(`acknowledged findings (${r.acknowledged.length}, Fw.Ops.Premise.acks; not failing):`);
    for (const a of r.acknowledged) {
      lines.push(`  ACK premise ${a.premise} on ${a.engine}: ${a.class} [${a.finding}${a.intermittent ? ", intermittent" : ""}]`);
      lines.push(`    theorems that assume it, not proved for this engine: ${a.theorems.join(", ")}`);
    }
  }
  lines.push(r.ok ? "premises: ok" : "premises: FAILED");
  return lines.join("\n");
}

// ---- cli ----------------------------------------------------------------------------------------------------------

export type PremiseArgs = { results: string[]; golden?: string; json: boolean };

export function parsePremiseArgs(argv: string[]): PremiseArgs {
  const a: PremiseArgs = { results: [], json: false };
  for (let i = 0; i < argv.length; i++) {
    const f = argv[i]!;
    if (f === "--json") { a.json = true; continue; }
    if (f !== "--results" && f !== "--golden") throw new UsageError(`unknown argument ${f}\n${PREMISES_USAGE}`);
    const v = argv[i + 1];
    if (v === undefined || v.startsWith("--")) throw new UsageError(`flag ${f} needs a value\n${PREMISES_USAGE}`);
    if (f === "--results") a.results.push(v); else a.golden = v;
    i++;
  }
  return a;
}

/** The tests the package declares (src/tests.mjs has no browser import, so loading it starts nothing). */
async function declaredTests(root: string): Promise<TestRef[]> {
  const m = (await import(pathToFileURL(join(root, "packages", "premise-tests", "src", "tests.mjs")).href)) as { TESTS: { id: string; premise: string }[] };
  return m.TESTS.map((t) => ({ id: t.id, premise: t.premise }));
}

export async function premisesCli(argv: string[], cwd: string): Promise<number> {
  try {
    const a = parsePremiseArgs(argv);
    const root = findRoot(cwd);
    const g = parseGolden(readFileSync(a.golden ?? join(root, "packages", "contracts", "golden", "ops", "premise.jsonl"), "utf8"));
    const declared = leanDeclared(root);
    let r: Report;
    if (a.results.length) {
      const files = readResults(a.results);
      if (files.length === 0) throw new UsageError(`no premise result files under ${a.results.join(", ")}`);
      const tests = new Map<string, TestRef>();
      for (const f of files) for (const t of f.tests) tests.set(`${t.id}\u0000${t.premise}`, t);
      r = report(g, [...tests.values()], workflowFiles(root), files.flatMap((f) => f.results), declared, [...new Set(files.map((f) => f.engine))], ledgerIds(root));
    } else {
      r = report(g, await declaredTests(root), workflowFiles(root), null, declared, [], ledgerIds(root));
    }
    console.log(a.json ? JSON.stringify(r, null, 2) : render(r, a.results.length > 0));
    return r.ok ? 0 : 3;
  } catch (e) {
    console.error(e instanceof Error ? e.message : String(e));
    return e instanceof UsageError ? 64 : 1;
  }
}
