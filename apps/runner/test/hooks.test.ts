import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir, userInfo } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { fwArgv, tokens, lex, cmdWords, cmdHash, identity, decideCap } from "../hooks/cap.mjs";
import { capMac, sha256 } from "../hooks/lib.mjs";
import { notification, verbOf } from "../hooks/emit.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const hook = (n: string) => join(here, "../hooks", n);
const run = (script: string, input: string, dir: string) =>
  spawnSync("node", [hook(script)], { input, env: { ...process.env, FW_CONSOLE_DIR: dir }, encoding: "utf8" });
const tmp = () => mkdtempSync(join(tmpdir(), "fw-hooks-"));
/** Lean `ops.actor` golden cases (generated by lean/scripts/OpsGolden.lean; never edited by hand). */
type ActorCase = { name: string; request: { agent_id?: unknown; agent_type?: unknown }; response: object };
const actorCases = readFileSync(join(here, "../../../packages/contracts/golden/ops/ops.actor.jsonl"), "utf8")
  .split("\n").filter(Boolean).map((l) => JSON.parse(l) as ActorCase);

/** Lean `ops.cap` golden cases (generated). */
type CapCase = { name: string; request: { agent_id?: unknown; agent_type?: unknown; tokens?: unknown[] }; response: { decision?: string; actor?: string; argv?: string[]; reason?: string; error?: string } };
const capCases = readFileSync(join(here, "../../../packages/contracts/golden/ops/ops.cap.jsonl"), "utf8")
  .split("\n").filter(Boolean).map((l) => JSON.parse(l) as CapCase);

const user = userInfo().username;
const dirty = {
  hook_event_name: "PostToolUse", agent_id: "a1b2", agent_type: "con-hooks", tool_name: "Bash",
  tool_use_id: "toolu_1", duration_ms: 123.4, cwd: `/Users/${user}/secret/place`, transcript_path: `/Users/${user}/x.jsonl`,
  tool_input: { command: `cat /Users/${user}/.ssh/id_rsa mail@example.com`, file_path: `/Users/${user}/a` },
  tool_response: { stdout: `owner ${user}@host /Users/${user}` }, last_assistant_message: `ping ${user}@example.com`,
};

describe("emit.mjs", () => {
  it("writes one line with only the allowed fields, silent, exit 0", () => {
    const d = tmp();
    const r = run("emit.mjs", JSON.stringify(dirty), d);
    expect(r.status).toBe(0);
    expect(r.stdout).toBe("");
    expect(r.stderr).toBe("");
    const txt = readFileSync(join(d, "spool", "a1b2.jsonl"), "utf8");
    const rec = JSON.parse(txt);
    expect(Object.keys(rec).sort()).toEqual(["agent_id", "agent_type", "duration_ms", "hook_event_name", "is_error", "tool_name", "tool_use_id", "ts", "verb"]);
    expect(rec).toMatchObject({ agent_id: "a1b2", hook_event_name: "PostToolUse", duration_ms: 123, is_error: false, verb: "cat" });
  });
  it("privacy: output has no /Users/, no username, no @", () => {
    const d = tmp();
    run("emit.mjs", JSON.stringify(dirty), d);
    run("emit.mjs", JSON.stringify({ ...dirty, hook_event_name: "PostToolUseFailure", error: `boom ${user}@x`, agent_id: undefined }), d);
    for (const f of readdirSync(join(d, "spool"))) {
      const t = readFileSync(join(d, "spool", f), "utf8");
      expect(t).not.toContain("/Users/");
      expect(t).not.toContain(user);
      expect(t).not.toContain("@");
    }
  });
  it("Notification: type, message length and the tool token only; never the message text", () => {
    const d = tmp();
    run("emit.mjs", JSON.stringify({ hook_event_name: "Notification", agent_id: "a1b2", agent_type: "builder", notification_type: "permission_prompt",
      message: "Claude needs your permission to use Bash for the hidden-detail", cwd: d }), d);
    const txt = readFileSync(join(d, "spool", "a1b2.jsonl"), "utf8");
    expect(JSON.parse(txt)).toMatchObject({ hook_event_name: "Notification", tool_name: "Bash", notification_type: "permission_prompt", message_len: "Claude needs your permission to use Bash for the hidden-detail".length });
    expect(txt).not.toContain("hidden-detail");
    expect(notification({ message: "x", notification_type: "Bad Type!" })).toEqual({ type: null, len: 1, tool: null });
  });
  it("verb: allowlisted first token or other; never a path", () => {
    expect(verbOf("pnpm test")).toBe("pnpm");
    expect(verbOf("  git status")).toBe("git");
    expect(verbOf("/Users/x/bin/node a.js")).toBe("other");
    expect(verbOf("FOO=1 pnpm x")).toBe("other");
    expect(verbOf(undefined)).toBeNull();
  });
  it("failure marks is_error; non-tool events leave it null", () => {
    const d = tmp();
    run("emit.mjs", JSON.stringify({ hook_event_name: "PostToolUseFailure", tool_name: "Read", duration_ms: 5 }), d);
    run("emit.mjs", JSON.stringify({ hook_event_name: "SubagentStart", agent_id: "z" }), d);
    expect(JSON.parse(readFileSync(join(d, "spool", "main.jsonl"), "utf8"))).toMatchObject({ is_error: true, verb: null });
    expect(JSON.parse(readFileSync(join(d, "spool", "z.jsonl"), "utf8").split("\n")[0]!)).toMatchObject({ is_error: null });
  });
  it("no console running: still just appends (nothing to connect to)", () => {
    expect(existsSync(join(tmp(), "api.json"))).toBe(false);
    expect(run("emit.mjs", JSON.stringify(dirty), tmp()).status).toBe(0);
  });
  it("bad payloads and unwritable spool: silent, exit 0", () => {
    for (const bad of ["", "not json", "[]", "null", "{\"hook_event_name\":5}", "\u0000\u0001", "x".repeat(200_000)]) {
      const d = tmp();
      const r = run("emit.mjs", bad, d);
      expect(r.status).toBe(0);
      expect(r.stdout + r.stderr).toBe("");
      expect(existsSync(join(d, "spool"))).toBe(false);
    }
    // "full disk" stand-in: the console dir is a file, so mkdir/append fail with ENOTDIR
    const f = join(tmp(), "afile");
    writeFileSync(f, "x");
    const r = run("emit.mjs", JSON.stringify(dirty), f);
    expect(r.status).toBe(0);
    expect(r.stdout + r.stderr).toBe("");
  });
  // Load-robust: bare node and the hook run interleaved in one loop, so both see the same machine load, and the test
  // compares their minima (the least-disturbed run of each), not an absolute median. Bound: the hook's best run costs
  // less than two bare node startups (measured 2026-10-18 at load ~22 on 8 cores: bare 27 ms, hook 33 ms, ratio 1.2).
  // Still caught: anything that costs about one node startup or more on every call, e.g. an accidental heavy import
  // (a node_modules package such as typescript), a child process spawn (git, pnpm), a synchronous network call or a
  // retry sleep. Not caught: a small regression below one node startup (~25-50 ms).
  it("timing: emit.mjs costs less than two bare node startups (interleaved minima)", () => {
    const d = tmp();
    const time = (f: () => unknown) => { const t = performance.now(); f(); return performance.now() - t; };
    const bareMs: number[] = [], hookMs: number[] = [];
    for (let i = 0; i < 15; i++) {
      bareMs.push(time(() => spawnSync("node", ["-e", ""])));
      hookMs.push(time(() => run("emit.mjs", JSON.stringify(dirty), d)));
    }
    const bare = Math.min(...bareMs), lo = Math.min(...hookMs);
    console.log(`emit.mjs latency ms: min ${lo.toFixed(0)}; bare node min ${bare.toFixed(0)}; ratio ${(lo / bare).toFixed(2)}`);
    expect(lo / bare).toBeLessThan(2);
  });
});

describe("cap.mjs", () => {
  it("tokenises like a shell and stops at control operators", () => {
    expect(tokens(`pnpm fw step done 'a b' "c d" e\\ f`)).toEqual(["pnpm", "fw", "step", "done", "a b", "c d", "e f"]);
    expect(fwArgv("pnpm fw status && rm -rf x")).toEqual(["status"]);
    expect(fwArgv("pnpm test")).toBeNull();
    expect(fwArgv("echo pnpm fw x")).toBeNull();
  });
  it("appends a capability with a valid MAC and a secret created 0600; silent", () => {
    const d = tmp();
    const input = JSON.stringify({ hook_event_name: "PreToolUse", tool_name: "Bash", tool_use_id: "toolu_9", agent_type: "owner-x",
      agent_id: "ag1", tool_input: { command: "pnpm fw step done  s1" } });
    const r = run("cap.mjs", input, d);
    expect(r.status).toBe(0);
    expect(r.stdout + r.stderr).toBe("");
    const rec = JSON.parse(readFileSync(join(d, "caps.jsonl"), "utf8"));
    const hash = sha256("step done s1");
    expect(rec).toMatchObject({ agent_type: "owner-x", agent_id: "ag1", tool_use_id: "toolu_9", cmd_hash: hash });
    expect(rec.cmd_hash).toBe(cmdHash(["step", "done", "s1"]));
    expect(rec.mac).toBe(capMac(readFileSync(join(d, "secret"), "utf8").trim(), "ag1", "owner-x", "toolu_9", hash));
    expect(JSON.stringify(rec)).not.toContain("/Users/");
  });
  it("ignores other commands and bad payloads", () => {
    const d = tmp();
    run("cap.mjs", JSON.stringify({ tool_name: "Bash", tool_use_id: "t", tool_input: { command: "ls" } }), d);
    run("cap.mjs", "garbage", d);
    expect(existsSync(join(d, "caps.jsonl"))).toBe(false);
  });
  it("main thread (no agent_id) has agent_id null and agent_type main, whatever its agent_type", () => {
    const d = tmp();
    run("cap.mjs", JSON.stringify({ tool_name: "Bash", tool_use_id: "t1", tool_input: { command: "pnpm fw status" } }), d);
    run("cap.mjs", JSON.stringify({ tool_name: "Bash", tool_use_id: "t2", agent_type: "lean-prover", tool_input: { command: "pnpm fw status" } }), d);
    const recs = readFileSync(join(d, "caps.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
    expect(recs.map((r) => [r.agent_id, r.agent_type])).toEqual([[null, "main"], [null, "main"]]);
  });
  it.each([
    ["forked internal agent (empty agent_type)", { agent_id: "a0123456789abcdef", agent_type: "" }, "unknown identity"],
    ["agent_id without agent_type", { agent_id: "a0123456789abcdef" }, "unknown identity"],
    ["empty agent_id", { agent_id: "", agent_type: "lean-prover" }, "unknown identity"],
    ["non-string agent_id", { agent_id: 7, agent_type: "lean-prover" }, "field agent_id: expected a string"],
  ])("fail closed: %s mints nothing, exit 2 with a reason", (_n, ids, reason) => {
    const d = tmp();
    const r = run("cap.mjs", JSON.stringify({ tool_name: "Bash", tool_use_id: "t1", ...ids, tool_input: { command: "pnpm fw status" } }), d);
    expect(r.status).toBe(2);
    expect(r.stdout).toBe("");
    expect(r.stderr).toContain(reason);
    expect(existsSync(join(d, "caps.jsonl"))).toBe(false);
  });
  it("unknown identity on a non-fw command: untouched (exit 0, silent)", () => {
    const d = tmp();
    const r = run("cap.mjs", JSON.stringify({ tool_name: "Bash", tool_use_id: "t1", agent_id: "a1", agent_type: "", tool_input: { command: "ls" } }), d);
    expect([r.status, r.stdout + r.stderr]).toEqual([0, ""]);
  });
  it("an agent typed main keeps its agent_id (never minted as the lead)", () => {
    const d = tmp();
    run("cap.mjs", JSON.stringify({ tool_name: "Bash", tool_use_id: "t1", agent_id: "a1", agent_type: "main", tool_input: { command: "pnpm fw status" } }), d);
    expect(JSON.parse(readFileSync(join(d, "caps.jsonl"), "utf8"))).toMatchObject({ agent_id: "a1", agent_type: "main" });
  });
  it.each(actorCases)("identity matches Lean ops.actor: $name", (c) => {
    expect(identity(c.request.agent_id, c.request.agent_type)).toEqual(c.response);
  });
  it.each(capCases.filter((c) => c.response.error === undefined))("decision matches Lean ops.cap: $name", (c) => {
    const d = decideCap(c.request.agent_id, c.request.agent_type, cmdWords(c.request.tokens as Parameters<typeof cmdWords>[0]));
    expect(d.decision).toBe(c.response.decision);
    if (d.decision === "mint") expect({ actor: d.actor, argv: d.argv }).toEqual({ actor: c.response.actor, argv: c.response.argv });
    else expect(d.reason).toBe(c.response.reason);
  });
  const call = (command: string, extra: object = {}) =>
    JSON.stringify({ tool_name: "Bash", tool_use_id: "t1", cwd: "/", tool_input: { command }, ...extra });
  const lines = (d: string, f: string) => (existsSync(join(d, f)) ? readFileSync(join(d, f), "utf8").trim().split("\n").map((l) => JSON.parse(l)) : []);
  it("a leading cd mints nothing and records the reason notFwPrefix; exit 0", () => {
    const d = tmp();
    const r = run("cap.mjs", call("cd apps/runner && pnpm fw status"), d);
    expect(r.status).toBe(0);
    expect(lines(d, "caps.jsonl")).toEqual([]);
    expect(lines(d, "capmiss.jsonl")).toMatchObject([{ reason: "notFwPrefix", tool_use_id: "t1" }]);
  });
  it("pnpm -s fw is notFwPrefix too", () => {
    const d = tmp();
    run("cap.mjs", call("pnpm -s fw land --dry b"), d);
    expect(lines(d, "capmiss.jsonl")).toMatchObject([{ reason: "notFwPrefix" }]);
  });
  it("lex drops redirects and stops at a top-level operator", () => {
    expect(lex("pnpm fw x 2>&1 | tail -5")).toEqual(["pnpm", "fw", "x", { redir: true }, { stop: true }]);
    expect(tokens("pnpm fw x >out.txt")).toEqual(["pnpm", "fw", "x"]);
    expect(tokens("pnpm fw x > out.txt y")).toEqual(["pnpm", "fw", "x", "y"]);
    expect(tokens("pnpm fw x >>log 2>/dev/null")).toEqual(["pnpm", "fw", "x"]);
    expect(tokens("pnpm fw x <in")).toEqual(["pnpm", "fw", "x"]);
    expect(tokens("pnpm fw x &>all")).toEqual(["pnpm", "fw", "x"]);
    expect(tokens("pnpm fw x >&2")).toEqual(["pnpm", "fw", "x"]);
    expect(tokens("pnpm fw 2>&1 land b")).toEqual(["pnpm", "fw", "land", "b"]);
    expect(tokens("pnpm fw land b 2")).toEqual(["pnpm", "fw", "land", "b", "2"]);
    expect(tokens("pnpm fw x '2>&1' | grep a")).toEqual(["pnpm", "fw", "x", "2>&1"]);
    expect(tokens("pnpm fw x || echo no")).toEqual(["pnpm", "fw", "x"]);
    expect(tokens("pnpm fw x & echo bg")).toEqual(["pnpm", "fw", "x"]);
  });
  it("a command that is not about fw leaves no note", () => {
    const d = tmp();
    expect(run("cap.mjs", call("cd x && ls"), d).status).toBe(0);
    expect(lines(d, "capmiss.jsonl")).toEqual([]);
  });
  it("2>&1 before a filter pipe mints for the bare command", () => {
    const d = tmp();
    const r = run("cap.mjs", call("pnpm fw status 2>&1 | tail"), d);
    expect(r.status).toBe(0);
    const caps = lines(d, "caps.jsonl");
    expect(caps).toHaveLength(1);
    expect(caps[0].cmd_hash).toBe(cmdHash(["status"]));
  });
  it("a plain pipe after the command still mints", () => {
    const d = tmp();
    expect(run("cap.mjs", call("pnpm fw status | tail"), d).status).toBe(0);
    expect(lines(d, "caps.jsonl")).toHaveLength(1);
  });
  it("a forked agent is unknownActor (exit 2, reason named)", () => {
    const d = tmp();
    const r = run("cap.mjs", call("pnpm fw status", { agent_id: "a1", agent_type: "" }), d);
    expect(r.status).toBe(2);
    expect(r.stderr).toContain("unknownActor");
  });
});

describe("emit.mjs: unseen spawns and background_tasks", () => {
  const start = { hook_event_name: "SubagentStart", agent_id: "wf1", agent_type: "explainer-rev6" };
  const lines = (d: string, f: string) => readFileSync(join(d, "spool", f), "utf8").trim().split("\n").map((l) => JSON.parse(l));
  it("SubagentStart with no guard marker adds a SpawnGuard observation seen_by subagent-start", () => {
    const d = tmp();
    run("emit.mjs", JSON.stringify(start), d);
    const [a, b] = lines(d, "wf1.jsonl");
    expect(a.hook_event_name).toBe("SubagentStart");
    expect(b).toMatchObject({ hook_event_name: "SpawnGuard", agent_id: "wf1", verb: "observed", seen_by: "subagent-start", role: "explainer-rev6" });
  });
  it("a guard marker of the same role is claimed once: no second record, the next start is unseen", () => {
    const d = tmp();
    mkdirSync(join(d, "spawn-pending"), { recursive: true });
    writeFileSync(join(d, "spawn-pending", `${Date.now()}-toolu_1.json`), JSON.stringify({ role: "explainer-rev6" }));
    run("emit.mjs", JSON.stringify(start), d);
    expect(lines(d, "wf1.jsonl")).toHaveLength(1);
    run("emit.mjs", JSON.stringify({ ...start, agent_id: "wf2" }), d);
    expect(lines(d, "wf2.jsonl")).toHaveLength(2);
  });
  it("SubagentStop keeps background_tasks as a count only", () => {
    const d = tmp();
    run("emit.mjs", JSON.stringify({ hook_event_name: "SubagentStop", agent_id: "q", background_tasks: [{ id: "t1", command: "secret cmd" }, { id: "t2" }] }), d);
    const t = readFileSync(join(d, "spool", "q.jsonl"), "utf8");
    expect(JSON.parse(t).background_tasks).toBe(2);
    expect(t).not.toContain("hidden-detail");
  });
});
