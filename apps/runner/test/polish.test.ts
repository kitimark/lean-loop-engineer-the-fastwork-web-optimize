      g(main, "worktree", "add", "-q", "-b", "feat", wt);
      const tip = body.slice(); tip[59] = "echo changed 60";
      writeFileSync(join(wt, n), tip.join("\n") + "\n");
      g(wt, "commit", "-qam", "builder");
