// The generated block of the lag note: the report between two marker lines, replaced in place so that no table cell is typed by hand.
export const BEGIN = '<!-- lag-report:begin (generated by packages/measure-webkit/src/lag/cli.mjs report --note; do not edit) -->';
export const END = '<!-- lag-report:end -->';

/** `text` with the lines between the markers replaced by `block`; throws when a marker is missing. */
export function fillBlock(text, block) {
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error('the note has no lag-report markers');
  return `${text.slice(0, a + BEGIN.length)}\n\n${block}\n\n${text.slice(b)}`;
}

/** The block between the markers of a note, or null. */
export function blockOf(text) {
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  return a < 0 || b < a ? null : text.slice(a + BEGIN.length, b).trim();
}
