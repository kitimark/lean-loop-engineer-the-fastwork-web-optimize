const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// Display math is set inline with \displaystyle, so a wide formula scrolls from its left edge.
// KaTeX writes an operator built from several atoms (`\mathbin{+\!\!+}` list append, `\mathop{+\!\!+}`, `\mathbin{::}`,
// `\mathbin{\langle|\rangle}`, and the monus `\mathbin{\dot-}`, written as an <mo> around a <mover>) as an <mo> that holds <mo>, <mtext> and <mspace> children. The HTML parser breaks that
// apart (the inner MO and MTEXT leave the MathML namespace), which draws a stray symbol on its own line. Each such
// <mo> becomes one <mo> carrying the concatenated text, so the docstrings and their review hashes stay unchanged.
const LEAF = String.raw`<(?:mo|mtext|mi)\b[^>]*>[^<]*<\/(?:mo|mtext|mi)>|<mspace\b[^>]*\/>`;
const NESTED_MO = new RegExp(String.raw`<mo\b([^>]*)>((?:${LEAF})+)<\/mo>`, 'g');
const DOT_MINUS = /<mo\b([^>]*)><mover accent="true"><mo>\u2212<\/mo><mo>\u02D9<\/mo><\/mover><\/mo>/g;
const MRROW_MO = new RegExp(String.raw`(<mo\b[^>]*>)<mrow>((?:${LEAF})+)<\/mrow><\/mo>`, 'g');
const flattenMo = (ml) => ml.replace(DOT_MINUS, '<mo$1>\u2238</mo>').replace(MRROW_MO, '$1$2</mo>').replace(NESTED_MO, (_, attrs, inner) => {
  const text = [...inner.matchAll(/<(?:mo|mtext|mi)\b[^>]*>([^<]*)<\/(?:mo|mtext|mi)>/g)].map((m) => m[1].replace(/[\u2063\s]/g, '')).join('');
  return `<mo${attrs}>${text}</mo>`;
});
// KaTeX wraps each formula in <semantics> with an <annotation encoding="application/x-tex"> copy of the TeX. The page
// shows only the MathML, so the wrapper and the copy go (lossless for display; the file stays under the host limit).
const stripSemantics = (ml) => ml.replace(/<annotation\b[^>]*>[^<]*<\/annotation>/g, '').replace(/<semantics>([\s\S]*?)<\/semantics>/g, '$1');
// More lossless shrinking, each a default the browser applies anyway: the KaTeX <span> around <math>; the xmlns (the HTML
// parser puts <math> in the MathML namespace); separator (not an attribute in MathML Core); and mathvariant="normal" on
// an <mi> that is not one Latin or Greek letter (only a single letter is italicised by default, text-transform: math-auto).
// A run of upright single-letter <mi> (KaTeX writes \mathrm{ab} that way) becomes one upright <mi>: same glyphs, no spacing between <mi>.
const shrink = (ml) => ml
  .replace(/^<span class="katex">([\s\S]*)<\/span>$/, '$1')
  .replace(/<math xmlns="http:\/\/www\.w3\.org\/1998\/Math\/MathML">/g, '<math>')
  .replace(/ separator="true"/g, '')
  .replace(/(?:<mi mathvariant="normal">[A-Za-z]<\/mi>){2,}/g, (run) => `<mi mathvariant="normal">${[...run.matchAll(/>([A-Za-z])</g)].map((m) => m[1]).join('')}</mi>`)
  .replace(/<mi mathvariant="normal">([^<]*)<\/mi>/g, (all, t) => (/^[A-Za-z\u0391-\u03A9\u03B1-\u03C9]$/.test(t) ? all : `<mi>${t}</mi>`));
const tex = (srcRaw, display) => {
  const src = srcRaw.replace(/\u2238/g, '\\dot-');
  const out = shrink(flattenMo(stripSemantics(katex.renderToString((display ? '\\displaystyle ' : '') + src,
    { displayMode: false, output: 'mathml', throwOnError: true, strict: 'error' }))));
  if (/<mo\b[^>]*><[a-z]/.test(out)) throw new Error(`nested <mo> in the MathML of: ${src.slice(0, 80)}`);
  return out;
};

