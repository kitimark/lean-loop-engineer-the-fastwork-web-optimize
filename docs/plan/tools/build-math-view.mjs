#!/usr/bin/env node
// Generates the "Math view" of docs/plan/loop-plan.html from the docstrings in
// research/kickoff/05-lean-sketch/Fw/Spec/*.lean and writes it between the mathview markers.
// Each docstring holds one English sentence and one or more $$...$$ blocks (PLAN §5.3). The TeX is
// rendered here with KaTeX 0.16.11 as MathML (browsers draw it natively), so the page needs no script,
// and a TeX parse error fails this script. Re-run after any change to the Lean files:
//   node docs/plan/tools/build-math-view.mjs          (writes the page)
//   node docs/plan/tools/build-math-view.mjs --check  (exits 1 if the page is out of date or the TeX does not parse)
// KaTeX comes from FW_KATEX (path to katex.js or katex.min.js of 0.16.11), else from `katex` resolvable
// from the repo. To get it: `npm install katex@0.16.11` in a scratch folder and set
// FW_KATEX=<folder>/node_modules/katex/dist/katex.min.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const specDir = join(root, 'research/kickoff/05-lean-sketch/Fw/Spec');
const pagePath = join(root, 'docs/plan/loop-plan.html');
const modules = ['Frames', 'Verdict', 'Flags', 'Cost', 'Lease', 'Stage'];
const KATEX_VERSION = '0.16.11';
const BEGIN = '<!-- mathview:begin (generated by docs/plan/tools/build-math-view.mjs; do not edit by hand) -->';
const END = '<!-- mathview:end -->';

const katex = (() => {
  const req = createRequire(join(root, 'package.json'));
  try {
    return req(process.env.FW_KATEX || 'katex');
  } catch {
    console.error(`KaTeX ${KATEX_VERSION} not found: set FW_KATEX to its katex.min.js (see the header of this script)`);
    process.exit(2);
  }
})();
if (katex.version !== KATEX_VERSION) {
  console.error(`KaTeX ${katex.version} found, ${KATEX_VERSION} required`);
  process.exit(2);
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// Display math is set inline with \displaystyle, so a wide formula scrolls from its left edge.
const tex = (src, display) =>
  katex.renderToString((display ? '\\displaystyle ' : '') + src, { displayMode: false, output: 'mathml', throwOnError: true, strict: 'error' });
const DECL = /^(\s*)(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable)\s+)*(theorem|lemma|def|abbrev|inductive|structure|class)\s+([^\s(:{[]+)/;

// Notation used in the docstrings (research/kickoff/10-automation-and-proof/04-lean-to-math.md §3).
const notation = [
  ['\\mathbb{N},\\ \\mathbb{Z}', 'Naturals {0, 1, 2, …} and integers. No floats anywhere; frame times are whole µs, lease times whole seconds.'],
  ['X^{*}', 'Finite lists over X; order and repeats matter.'],
  ['[\\,],\\ x :: xs,\\ xs \\mathbin{+\\!\\!+} ys', 'Empty list, prepend, append.'],
  ['\\lvert xs \\rvert', 'Length, counting repeats.'],
  ['\\#\\{\\, i : P(x_i) \\,\\}', 'How many positions satisfy P (repeats counted).'],
  ['[P]', '1 if P holds, else 0.'],
  ['\\lfloor a / b \\rfloor,\\ a \\mathbin{\\dot-} b', 'Natural-number division rounds down; subtraction on ℕ stops at 0.'],
  ['-xs', 'Every element negated.'],
  ['f[p \\mapsto v]', 'f with the value at p replaced by v.'],
  ['X_\\bot,\\ \\bot', 'An optional value; ⊥ means none.'],
  ['s.\\mathit{field},\\ \\mathrm{step}(s, c)_1', 'A record field; the first part of a pair.'],
  ['\\mathrm{ok}(x),\\ \\mathrm{error}(m)', 'A success or a failure result.'],
  [null, 'Bool-valued f', 'Used as a statement: "f(x)" means f(x) = true.'],
];

// Text with inline $...$ math and `code`, as HTML.
function inline(text) {
  return text.split(/(\$[^$]+\$|`[^`]+`)/).map((part) => {
    if (part.startsWith('$') && part.endsWith('$') && part.length > 2) return `<span class="mv-i">${tex(part.slice(1, -1), false)}</span>`;
    if (part.startsWith('`') && part.endsWith('`') && part.length > 2) return `<code>${esc(part.slice(1, -1))}</code>`;
    return esc(part);
  }).join('');
}

// A docstring body as an ordered list of text paragraphs and display-math blocks.
function segments(body) {
  const out = [];
  body.split(/\$\$([\s\S]*?)\$\$/).forEach((piece, i) => {
    if (i % 2 === 1) { out.push({ math: piece.trim() }); return; }
    for (const para of piece.split(/\n\s*\n/)) {
      const t = para.split('\n').map((l) => l.trim()).join(' ').trim();
      if (t) out.push({ text: t });
    }
  });
  return out;
}

function parseModule(name) {
  const file = join(specDir, `${name}.lean`);
  const lines = readFileSync(file, 'utf8').split('\n');
  const heading = (lines.find((l) => /^# /.test(l)) || `# ${name}`).slice(2).trim();
  const ns = (lines.find((l) => /^namespace /.test(l)) || '').replace(/^namespace\s+/, '').trim();
  const decls = [];
  let parent = '';
  for (let i = 0; i < lines.length; i++) {
    const top = DECL.exec(lines[i]);
    if (top && top[1] === '') parent = top[3];
    if (!/^\s*\/--/.test(lines[i])) continue;
    const doc = [];
    let j = i;
    for (;; j++) {
      doc.push(lines[j]);
      if (/-\/\s*$/.test(lines[j])) break;
    }
    let k = j + 1;
    while (k < lines.length && lines[k].trim() === '') k++;
    // A local definition after `where` has no keyword: `  check (r : Registry) … :=`.
    const local = /^(\s+)([A-Za-z_][\w']*)\s*[({[:]/.exec(lines[k] || '');
    const m = DECL.exec(lines[k] || '') || (local && [local[0], local[1], 'def', local[2]]);
    if (!m) throw new Error(`${name}.lean:${i + 1}: docstring not followed by a declaration`);
    const nested = m[1] !== '';
    if (!nested) parent = m[3];
    const short = nested ? `${parent}.${m[3]}` : m[3];
    const body = doc.join('\n').replace(/^\s*\/--\s?/, '').replace(/\s*-\/\s*$/, '');
    const indent = Math.min(...body.split('\n').slice(1).filter((l) => l.trim()).map((l) => l.match(/^\s*/)[0].length), 99);
    const dedented = body.split('\n').map((l, n) => (n === 0 ? l : l.slice(Math.min(indent, l.match(/^\s*/)[0].length)))).join('\n');
    const segs = segments(dedented);
    if (!segs.some((s) => s.math)) throw new Error(`${name}.lean:${k + 1}: ${short} has no $$ math`);
    decls.push({ name: short, full: `${ns}.${short}`, kind: m[2], line: k + 1, segs });
    i = j;
  }
  return { name, heading, ns, file: relative(root, file), decls };
}

const isThm = (d) => d.kind === 'theorem' || d.kind === 'lemma';

function entry(d) {
  let firstText = true;
  const parts = d.segs.map((s) => {
    try {
      if (s.math) return `<div class="mv-math">${tex(s.math, true)}</div>`;
      const cls = firstText ? 'mv-en' : 'mv-note';
      firstText = false;
      return `<p class="${cls}">${inline(s.text)}</p>`;
    } catch (e) {
      throw new Error(`${d.full} (line ${d.line}): ${e.message}`);
    }
  });
  return [
    `<div class="mv-entry${isThm(d) ? ' thm' : ''}">`,
    `<div class="mv-head"><code class="mv-name" title="${esc(d.full)}">${esc(d.name)}</code><span class="chip">${d.kind}</span><span class="mv-loc">l.${d.line}</span></div>`,
    ...parts,
    '</div>',
  ].join('\n');
}

function render(mods, commit) {
  const all = mods.flatMap((m) => m.decls);
  const nThm = all.filter(isThm).length;
  const out = [
    BEGIN,
    '<details>',
    '<summary>Notation</summary>',
    '<div class="tbl mv-notation"><table>',
    '<thead><tr><th>Symbol</th><th>Meaning</th></tr></thead>',
    '<tbody>',
    ...notation.map(([t, a, b]) => (t === null
      ? `<tr><td>${esc(a)}</td><td>${esc(b)}</td></tr>`
      : `<tr><td><span class="mv-i">${tex(t, false)}</span></td><td>${esc(a)}</td></tr>`)),
    '</tbody></table></div>',
    '</details>',
    `<nav class="mv-jump" aria-label="Math view modules">${mods.map((m) => `<a href="#mv-${m.name.toLowerCase()}">${esc(m.name)}</a>`).join('')}</nav>`,
    '<div class="mv-all">',
    `<p class="mv-count">${all.length} declarations in ${mods.length} modules: ${nThm} theorems, ${all.length - nThm} definitions. Generated from <span class="mono">research/kickoff/05-lean-sketch/Fw/Spec</span> at <span class="mono">${esc(commit)}</span>; formulas pre-rendered as MathML by KaTeX ${KATEX_VERSION}.</p>`,
  ];
  for (const m of mods) {
    const thms = m.decls.filter(isThm);
    const defs = m.decls.filter((d) => !isThm(d));
    out.push(
      `<div class="mv-mod" id="mv-${m.name.toLowerCase()}">`,
      `<div class="mv-modhead"><h3>${esc(m.name)}</h3><span class="mv-sub">${esc(m.heading)}</span><span class="mv-file mono">${esc(m.file.replace(/^research\/kickoff\/05-lean-sketch\//, ''))} · ${thms.length} theorems · ${defs.length} definitions</span></div>`,
      ...thms.map(entry),
      `<details class="mv-defs"><summary>Definitions used (${defs.length})</summary>`,
      ...defs.map(entry),
      '</details>',
      '</div>',
    );
  }
  out.push('</div>', END);
  return out.join('\n');
}

const mods = modules.map(parseModule);
let commit = 'working tree';
try {
  commit = execFileSync('git', ['log', '-1', '--format=%h', '--', relative(root, specDir)], { cwd: root, encoding: 'utf8' }).trim() || commit;
  const dirty = execFileSync('git', ['status', '--porcelain', '--', relative(root, specDir)], { cwd: root, encoding: 'utf8' }).trim();
  if (dirty) commit += ' + uncommitted changes';
} catch { /* not a git checkout: keep "working tree" */ }

const page = readFileSync(pagePath, 'utf8');
const a = page.indexOf(BEGIN);
const b = page.indexOf(END);
if (a < 0 || b < a) throw new Error(`markers not found in ${relative(root, pagePath)}`);
const next = page.slice(0, a) + render(mods, commit) + page.slice(b + END.length);
const total = mods.reduce((n, m) => n + m.decls.length, 0);
if (process.argv.includes('--check')) {
  if (next !== page) { console.error('math view is out of date: run node docs/plan/tools/build-math-view.mjs'); process.exit(1); }
  console.log(`math view up to date (${total} declarations)`);
} else {
  writeFileSync(pagePath, next);
  console.log(`wrote ${total} declarations from ${mods.length} modules into ${relative(root, pagePath)}`);
}
