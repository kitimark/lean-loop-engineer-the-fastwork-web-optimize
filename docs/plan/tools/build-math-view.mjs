#!/usr/bin/env node
// Generates the "Math view" of docs/plan/loop-plan.html from the Lean core lean/ (fwcore) and writes it
// between the mathview markers, plus the review summary between the mathview-review markers.
// The source is `lake exe mathview` (lean/README.md): a JSON export of every Fw declaration, whose
// docstring holds one English sentence and one or more $$...$$ blocks (PLAN §5.3). The TeX is rendered
// here with KaTeX 0.16.11 as MathML (browsers draw it natively), so the page needs no script, and a TeX
// parse error fails this script. The review status of each declaration comes from the table rows of
// research/notes/*/*-math-review-*.md (see reviews() below). Re-run after any change to lean/ or a record:
//   node docs/plan/tools/build-math-view.mjs                 (runs lake build, mathview --lint, mathview; writes the page)
//   node docs/plan/tools/build-math-view.mjs --json <file>   (uses a saved `lake exe mathview` export instead of lake)
//   node docs/plan/tools/build-math-view.mjs --check         (exits 1 if the page is out of date or the TeX does not parse)
// KaTeX comes from FW_KATEX (path to katex.js or katex.min.js of 0.16.11), else from `katex` resolvable
// from the repo (root devDependency: `pnpm install`).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const leanDir = join(root, 'lean');
const notesDir = join(root, 'research/notes');
const pagePath = join(root, 'docs/plan/loop-plan.html');
// Module order on the page; a module not listed (a new Fw/ subtree) follows in name order.
const order = ['Fw.Spec.Frames', 'Fw.Spec.Verdict', 'Fw.Spec.Null', 'Fw.Spec.Screen', 'Fw.Spec.Cost', 'Fw.Spec.Flags',
  'Fw.Spec.Stage', 'Fw.Spec.Lease', 'Fw.Spec.DeviceQueue', 'Fw.Spec.ArtifactKey', 'Fw.Console', 'Fw.Board'];
const AXIOMS = ['propext', 'Classical.choice', 'Quot.sound'];
const KATEX_VERSION = '0.16.11';
const BEGIN = '<!-- mathview:begin (generated by docs/plan/tools/build-math-view.mjs; do not edit by hand) -->';
const END = '<!-- mathview:end -->';
const RBEGIN = '<!-- mathview-review:begin (generated by docs/plan/tools/build-math-view.mjs; do not edit by hand) -->';
const REND = '<!-- mathview-review:end -->';
const SKETCH_RECORD = 'research/notes/2026/10-17-math-review-fw-spec.md';
const FWCORE_RECORD = 'research/notes/2026/10-17-math-review-fwcore.md';

const katex = (() => {
  const req = createRequire(join(root, 'package.json'));
  try {
    return req(process.env.FW_KATEX || 'katex');
  } catch {
    console.error(`KaTeX ${KATEX_VERSION} not found: set FW_KATEX to its katex.min.js (see the header of this script)`);
    process.exit(2);
  }
})();
if (katex.version !== KATEX_VERSION) {
  console.error(`KaTeX ${katex.version} found, ${KATEX_VERSION} required`);
  process.exit(2);
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// Display math is set inline with \displaystyle, so a wide formula scrolls from its left edge.
const tex = (src, display) =>
  katex.renderToString((display ? '\\displaystyle ' : '') + src, { displayMode: false, output: 'mathml', throwOnError: true, strict: 'error' });

// Notation used in the docstrings (research/kickoff/10-automation-and-proof/04-lean-to-math.md §3).
const notation = [
  ['\\mathbb{N},\\ \\mathbb{Z}', 'Naturals {0, 1, 2, …} and integers. No floats anywhere; times are whole µs, ns, ms or seconds (the unit is in the name).'],
  ['\\mathbb{Q}', 'Exact fractions, used for probabilities.'],
  ['X^{*}', 'Finite lists over X; order and repeats matter.'],
  ['[\\,],\\ x :: xs,\\ xs \\mathbin{+\\!\\!+} ys', 'Empty list, prepend, append.'],
  ['\\lvert xs \\rvert', 'Length, counting repeats.'],
  ['\\#\\{\\, i : P(x_i) \\,\\}', 'How many positions satisfy P (repeats counted).'],
  ['[P]', '1 if P holds, else 0.'],
  ['\\lfloor a / b \\rfloor,\\ a \\mathbin{\\dot-} b', 'Natural-number division rounds down; subtraction on ℕ stops at 0.'],
  ['-xs', 'Every element negated.'],
  ['f[p \\mapsto v]', 'f with the value at p replaced by v.'],
  ['X_\\bot,\\ \\bot', 'An optional value; ⊥ means none.'],
  ['s.\\mathit{field},\\ \\mathrm{step}(s, c)_1', 'A record field; the first part of a pair.'],
  ['\\mathrm{ok}(x),\\ \\mathrm{error}(m)', 'A success or a failure result.'],
  [null, 'Bool-valued f', 'Used as a statement: "f(x)" means f(x) = true.'],
];

// Text with inline $...$ math and `code`, as HTML.
function inline(text) {
  return text.split(/(\$[^$]+\$|`[^`]+`)/).map((part) => {
    if (part.startsWith('$') && part.endsWith('$') && part.length > 2) return `<span class="mv-i">${tex(part.slice(1, -1), false)}</span>`;
    if (part.startsWith('`') && part.endsWith('`') && part.length > 2) return `<code>${esc(part.slice(1, -1))}</code>`;
    return esc(part);
  }).join('');
}

// A docstring body as an ordered list of text paragraphs and display-math blocks.
function segments(body) {
  const out = [];
  body.split(/\$\$([\s\S]*?)\$\$/).forEach((piece, i) => {
    if (i % 2 === 1) { out.push({ math: piece.trim() }); return; }
    for (const para of piece.split(/\n\s*\n/)) {
      const t = para.split('\n').map((l) => l.trim()).join(' ').trim();
      if (t) out.push({ text: t });
    }
  });
  return out;
}

// The `lake exe mathview` export: from --json <file>, else built and linted here.
function loadExport() {
  const i = process.argv.indexOf('--json');
  if (i >= 0) return JSON.parse(readFileSync(process.argv[i + 1], 'utf8'));
  const lake = (args, opts = {}) => execFileSync('lake', args, { cwd: leanDir, encoding: 'utf8', maxBuffer: 1 << 28, ...opts });
  try {
    lake(['build'], { stdio: ['ignore', 'ignore', 'inherit'] });
    lake(['exe', 'mathview', '--lint'], { stdio: ['ignore', 'ignore', 'inherit'] });
    return JSON.parse(lake(['exe', 'mathview']));
  } catch (e) {
    console.error(`lake build / mathview --lint failed in lean/ (${e.message.split('\n')[0]}); fix lean/ or pass --json <file>`);
    process.exit(1);
  }
}

// Review status per declaration, from the review records. A record row reads
//   | `Fw.Null.pAt_le` | agree | 1234567890 | 9876543210 | note |
// (full name, `agree` or `disagree`, optional mathview stmtHash, optional mathview mathHash, optional note).
// Hash cells are recognised by being all digits, so the older rows `| name | verdict | stmtHash | note |` and
// `| name | verdict |` keep working: a row is checked on the hashes it carries. A row is stale when its stmtHash
// differs from the export (the Lean statement changed) or its mathHash differs (the docstring's English, $$ math
// or notes changed); a declaration with no row is pending.
// Precedence: each record's frontmatter carries `round: <n>`; for a declaration, the row of the highest round
// wins (within one record, the last row). A record without `round:` ranks below every numbered round, ordered by
// file name among such records (a warning names it when it has rows). Two records with the same round fail.
function reviews() {
  const out = new Map();
  const files = [];
  for (const year of existsSync(notesDir) ? readdirSync(notesDir).sort() : []) {
    const dir = join(notesDir, year);
    try {
      for (const f of readdirSync(dir).sort()) if (/-math-review-.*\.md$/.test(f)) files.push(join(dir, f));
    } catch { /* not a folder */ }
  }
  const records = files.map((file) => {
    const text = readFileSync(file, 'utf8');
    const front = /^---\n([\s\S]*?)\n---\n/.exec(text);
    const round = front && /^round:\s*(\d+)\s*$/m.exec(front[1]);
    return { file, text, round: round ? Number(round[1]) : null };
  });
  const seen = new Map();
  for (const r of records) {
    if (r.round === null) continue;
    if (seen.has(r.round)) {
      console.error(`math review records ${relative(root, seen.get(r.round))} and ${relative(root, r.file)} both have round: ${r.round}`);
      process.exit(1);
    }
    seen.set(r.round, r.file);
  }
  // Ascending precedence: unnumbered records (by name) first, then by round; later rows overwrite earlier ones.
  records.sort((a, b) => (a.round ?? -1) - (b.round ?? -1) || (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));
  const digits = (c) => { const h = (c || '').replace(/`/g, ''); return /^\d+$/.test(h) ? h : null; };
  for (const { file, text, round } of records) {
    let rows = 0;
    for (const line of text.split('\n')) {
      const cells = line.split('|').map((c) => c.trim()).slice(1, -1);
      if (cells.length < 2) continue;
      const name = /^`(Fw\.[^`]+)`$/.exec(cells[0]);
      const verdict = /^\**(agree|disagree)\**$/i.exec(cells[1]);
      if (!name || !verdict) continue;
      const hash = digits(cells[2]);
      const mathHash = hash ? digits(cells[3]) : null;
      out.set(name[1], { verdict: verdict[1].toLowerCase(), hash, mathHash, file: relative(root, file) });
      rows++;
    }
    if (rows && round === null) console.error(`warning: ${relative(root, file)} has review rows but no \`round:\` in its frontmatter; it ranks below every numbered round`);
  }
  return out;
}

function status(d, recs) {
  const r = recs.get(d.name);
  if (!r) return { key: 'pending', label: 'review pending', cls: 'mv-pend' };
  const stmtStale = r.hash && r.hash !== String(d.stmtHash);
  const mathStale = r.mathHash && r.mathHash !== String(d.mathHash);
  if (stmtStale || mathStale) {
    const why = [stmtStale ? 'Lean statement' : null, mathStale ? 'docstring' : null].filter(Boolean).join(' and ');
    return { key: 'stale', label: 'review stale', cls: 'open', file: `${r.file} (${why} changed since the review)` };
  }
  return r.verdict === 'agree'
    ? { key: 'agree', label: 'agree', cls: 'ok', file: r.file }
    : { key: 'disagree', label: 'disagree', cls: 'bad', file: r.file };
}

const isThm = (d) => d.kind === 'theorem' || d.kind === 'lemma';
// Fw.Flags.Part.mem_all -> Part.mem_all (the namespace after Fw is the module's own).
const short = (name) => { const p = name.split('.'); return p.slice(p.length > 2 ? 2 : 1).join('.'); };
const modFile = (m) => `${m.replace(/\./g, '/')}.lean`;
const modId = (m) => `mv-${m.replace(/^Fw\./, '').replace(/\./g, '-').toLowerCase()}`;
const modLabel = (m) => m.split('.').pop();

function heading(m) {
  const file = join(leanDir, modFile(m));
  const line = existsSync(file) ? readFileSync(file, 'utf8').split('\n').find((l) => /^# /.test(l)) : null;
  return line ? line.slice(2).trim() : m;
}

function entry(d) {
  const body = d.doc.replace(/\s+$/, '');
  const indent = Math.min(...body.split('\n').slice(1).filter((l) => l.trim()).map((l) => l.match(/^\s*/)[0].length), 99);
  const dedented = body.split('\n').map((l, n) => (n === 0 ? l : l.slice(Math.min(indent, l.match(/^\s*/)[0].length)))).join('\n');
  const segs = segments(dedented);
  if (!segs.some((s) => s.math)) throw new Error(`${d.name} (${d.module} l.${d.line}): no $$ math`);
  let firstText = true;
  const parts = segs.map((s) => {
    try {
      if (s.math) return `<div class="mv-math">${tex(s.math, true)}</div>`;
      const cls = firstText ? 'mv-en' : 'mv-note';
      firstText = false;
      return `<p class="${cls}">${inline(s.text)}</p>`;
    } catch (e) {
      throw new Error(`${d.name} (${d.module} l.${d.line}): ${e.message}`);
    }
  });
  const st = d.status;
  const chip = `<span class="chip ${st.cls}"${st.file ? ` title="${esc(st.file)}"` : ''}>${st.label}</span>`;
  return [
    `<div class="mv-entry${isThm(d) ? ' thm' : ''}">`,
    `<div class="mv-head"><code class="mv-name" title="${esc(d.name)}">${esc(short(d.name))}</code><span class="chip">${d.kind}</span>${chip}<span class="mv-loc">l.${d.line}</span></div>`,
    ...parts,
    '</div>',
  ].join('\n');
}

const tally = (ds) => {
  const n = { agree: 0, disagree: 0, stale: 0, pending: 0 };
  for (const d of ds) n[d.status.key]++;
  return n;
};
const tallyText = (n) => [
  `${n.agree} agree`, `${n.disagree} disagree`, ...(n.stale ? [`${n.stale} stale`] : []), `${n.pending} pending`,
].join(' / ');

function render(mods, all, commit) {
  const nThm = all.filter(isThm).length;
  const out = [
    BEGIN,
    '<details>',
    '<summary>Notation</summary>',
    '<div class="tbl mv-notation"><table>',
    '<thead><tr><th>Symbol</th><th>Meaning</th></tr></thead>',
    '<tbody>',
    ...notation.map(([t, a, b]) => (t === null
      ? `<tr><td>${esc(a)}</td><td>${esc(b)}</td></tr>`
      : `<tr><td><span class="mv-i">${tex(t, false)}</span></td><td>${esc(a)}</td></tr>`)),
    '</tbody></table></div>',
    '</details>',
    `<nav class="mv-jump" aria-label="Math view modules">${mods.map((m) => `<a href="#${modId(m.name)}">${esc(modLabel(m.name))}</a>`).join('')}</nav>`,
    '<div class="mv-all">',
    `<p class="mv-count">${all.length} declarations in ${mods.length} modules: ${nThm} theorems, ${all.length - nThm} definitions. Review: ${tallyText(tally(all))}. Generated from <span class="mono">lake exe mathview</span> on <span class="mono">lean/</span> at <span class="mono">${esc(commit)}</span>; formulas pre-rendered as MathML by KaTeX ${KATEX_VERSION}.</p>`,
  ];
  for (const m of mods) {
    const thms = m.decls.filter(isThm);
    const defs = m.decls.filter((d) => !isThm(d));
    const n = tally(m.decls);
    out.push(
      `<div class="mv-mod" id="${modId(m.name)}">`,
      `<div class="mv-modhead"><h3>${esc(modLabel(m.name))}</h3><span class="mv-sub">${esc(heading(m.name))}</span><span class="mv-file mono">${esc(modFile(m.name))} · ${thms.length} theorems · ${defs.length} definitions · ${n.agree}/${m.decls.length} reviewed</span></div>`,
      ...thms.map(entry),
      `<details class="mv-defs"><summary>Definitions used (${defs.length})</summary>`,
      ...defs.map(entry),
      '</details>',
      '</div>',
    );
  }
  out.push('</div>', END);
  return out.join('\n');
}

// The review panel above the view: chip, tally, records, axioms.
function renderReview(all, commit) {
  const n = tally(all);
  const done = n.agree === all.length;
  const record = existsSync(join(root, FWCORE_RECORD))
    ? `<a href="../../${FWCORE_RECORD}">${esc(FWCORE_RECORD.split('/').pop())}</a>`
    : `<span class="mono">${esc(FWCORE_RECORD.split('/').pop())}</span> (not written yet)`;
  const clean = all.every((d) => d.sorryFree && d.axioms.every((a) => AXIOMS.includes(a)));
  const nThm = all.filter(isThm).length;
  return [
    RBEGIN,
    `<h3><a class="chip ${done ? 'ok' : 'open'}" href="#mv-review">${done ? 'reviewed' : 'review pending'}</a> ${tallyText(n)}</h3>`,
    `<p id="mv-review">Each declaration shows its status: <i>agree</i> or <i>disagree</i> from a math-reviewer record, <i>review stale</i> when the Lean statement or, for rows that carry a docstring hash, the docstring changed after the review, <i>review pending</i> when no record covers it yet. Record for <span class="mono">lean/</span>: ${record}. The protocol: write its own math from the Lean, then compare it clause by clause with the docstring (ℕ vs ℤ, every hypothesis, ≤ vs &lt;, rounding, empty lists, ties, direction of ⇒ and ⇔).</p>`,
    `<p>${clean
      ? `At <span class="mono">${esc(commit)}</span> all ${all.length} declarations (${nThm} theorems) are free of <code>sorry</code> and use only the standard axioms (<code>propext</code>, <code>Classical.choice</code>, <code>Quot.sound</code>), checked by <code>lake exe mathview --lint</code>.`
      : `At <span class="mono">${esc(commit)}</span> some declarations use <code>sorry</code> or a non-standard axiom.`} The kickoff sketch's 72 declarations were reviewed earlier (<a href="../../${SKETCH_RECORD}">72 agree / 0 disagree</a>); that record does not cover <span class="mono">lean/</span>.</p>`,
    REND,
  ].join('\n');
}

const recs = reviews();
const exported = loadExport();
for (const d of exported) d.status = status(d, recs);
const byMod = new Map();
for (const d of exported) (byMod.get(d.module) || byMod.set(d.module, []).get(d.module)).push(d);
const names = [...order.filter((m) => byMod.has(m)), ...[...byMod.keys()].filter((m) => !order.includes(m)).sort()];
const mods = names.map((name) => ({ name, decls: byMod.get(name).sort((x, y) => x.line - y.line) }));
const all = mods.flatMap((m) => m.decls);

let commit = 'working tree';
try {
  const git = (args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  commit = git(['log', '-1', '--format=%h', '--', 'lean']) || commit;
  if (git(['status', '--porcelain', '--', 'lean'])) commit += ' + uncommitted changes';
} catch { /* not a git checkout: keep "working tree" */ }

const page = readFileSync(pagePath, 'utf8');
const splice = (text, begin, end, content) => {
  const a = text.indexOf(begin);
  const b = text.indexOf(end);
  if (a < 0 || b < a) throw new Error(`markers ${begin.slice(0, 24)}… not found in ${relative(root, pagePath)}`);
  return text.slice(0, a) + content + text.slice(b + end.length);
};
const next = splice(splice(page, BEGIN, END, render(mods, all, commit)), RBEGIN, REND, renderReview(all, commit));
const summary = `${all.length} declarations from ${mods.length} modules; review ${tallyText(tally(all))}`;
if (process.argv.includes('--check')) {
  if (next !== page) { console.error('math view is out of date: run node docs/plan/tools/build-math-view.mjs'); process.exit(1); }
  console.log(`math view up to date (${summary})`);
} else {
  writeFileSync(pagePath, next);
  console.log(`wrote ${summary} into ${relative(root, pagePath)}`);
}
