// Text with inline $...$ math and `code`, as HTML.
function inline(text) {
  return text.split(/(\$[^$]+\$|`[^`]+`)/).map((part) => {
    if (part.startsWith('$') && part.endsWith('$') && part.length > 2) return `<span class="mv-i">${tex(part.slice(1, -1), false)}</span>`;
    if (part.startsWith('`') && part.endsWith('`') && part.length > 2) return `<code>${esc(part.slice(1, -1))}</code>`;
    return esc(part);
  }).join('');
}

// A docstring body as an ordered list of text paragraphs and display-math blocks.
function segments(body) {
  const out = [];
  body.split(/\$\$([\s\S]*?)\$\$/).forEach((piece, i) => {
    if (i % 2 === 1) { out.push({ math: piece.trim() }); return; }
    for (const para of piece.split(/\n\s*\n/)) {
      const t = para.split('\n').map((l) => l.trim()).join(' ').trim();
      if (t) out.push({ text: t });
    }
  });
  return out;
}

// The `lake exe mathview` export: from --json <file>, else the cached export of lean/scripts/mathview-cached.sh
// (one build + lint + export per source state; a hit runs no lake at all). The lint decision stays in Lean.
function loadExport() {
  const i = process.argv.indexOf('--json');
  if (i >= 0) return JSON.parse(readFileSync(process.argv[i + 1], 'utf8'));
  try {
    const path = execFileSync('sh', [join(leanDir, 'scripts/mathview-cached.sh'), '--build'],
      { cwd: leanDir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }).trim();
    return JSON.parse(readFileSync(join(leanDir, path), 'utf8'));
  } catch (e) {
    console.error(`lake build / mathview --lint failed in lean/ (${e.message.split('\n')[0]}); fix lean/ or pass --json <file>`);
    process.exit(1);
  }
}

// Review status per declaration, from the review records. A record row reads
//   | `Fw.Null.pAt_le` | agree | 1234567890 | 9876543210 | note |
// (full name, `agree` or `disagree`, optional mathview stmtHash, optional mathview mathHash, optional note).
// Hash cells are recognised by being all digits, so the older rows `| name | verdict | stmtHash | note |` and
// `| name | verdict |` keep working: a row is checked on the hashes it carries. A row is stale when its stmtHash
// differs from the export (the Lean statement changed) or its mathHash differs (the docstring's English, $$ math
// or notes changed); a declaration with no row is pending.
// Precedence: each record's frontmatter carries `round: <n>`; for a declaration, the row of the highest round
// wins (within one record, the last row). A record without `round:` ranks below every numbered round, ordered by
// file name among such records (a warning names it when it has rows). Two records with the same round fail.
function reviews() {
  const out = new Map();
  const files = [];
  for (const year of existsSync(notesDir) ? readdirSync(notesDir).sort() : []) {
    const dir = join(notesDir, year);
    try {
      for (const f of readdirSync(dir).sort()) if (/-math-review-.*\.md$/.test(f)) files.push(join(dir, f));
    } catch { /* not a folder */ }
  }
  const records = files.map((file) => {
    const text = readFileSync(file, 'utf8');
    const front = /^---\n([\s\S]*?)\n---\n/.exec(text);
    const round = front && /^round:\s*(\d+)\s*$/m.exec(front[1]);
    return { file, text, round: round ? Number(round[1]) : null };
  });
  const seen = new Map();
  for (const r of records) {
    if (r.round === null) continue;
    if (seen.has(r.round)) {
      console.error(`math review records ${relative(root, seen.get(r.round))} and ${relative(root, r.file)} both have round: ${r.round}`);
      process.exit(1);
    }
    seen.set(r.round, r.file);
  }
  // Ascending precedence: unnumbered records (by name) first, then by round; later rows overwrite earlier ones.
  records.sort((a, b) => (a.round ?? -1) - (b.round ?? -1) || (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));
  const digits = (c) => { const h = (c || '').replace(/`/g, ''); return /^\d+$/.test(h) ? h : null; };
  for (const { file, text, round } of records) {
    let rows = 0;
    for (const line of text.split('\n')) {
      const cells = line.split('|').map((c) => c.trim()).slice(1, -1);
      if (cells.length < 2) continue;
      const name = /^`(Fw\.[^`]+)`$/.exec(cells[0]);
      const verdict = /^\**(agree|disagree)\**$/i.exec(cells[1]);
      if (!name || !verdict) continue;
      const hash = digits(cells[2]);
      const mathHash = hash ? digits(cells[3]) : null;
      out.set(name[1], { verdict: verdict[1].toLowerCase(), hash, mathHash, file: relative(root, file) });
      rows++;
    }
    if (rows && round === null) console.error(`warning: ${relative(root, file)} has review rows but no \`round:\` in its frontmatter; it ranks below every numbered round`);
  }
  return out;
}

function status(d, recs) {
  const r = recs.get(d.name);
  if (!r) return { key: 'pending', label: 'review pending', cls: 'mv-pend' };
  const stmtStale = r.hash && r.hash !== String(d.stmtHash);
  const mathStale = r.mathHash && r.mathHash !== String(d.mathHash);
  if (stmtStale || mathStale) {
    const why = [stmtStale ? 'Lean statement' : null, mathStale ? 'docstring' : null].filter(Boolean).join(' and ');
    return { key: 'stale', label: 'review stale', cls: 'open', file: `${r.file} (${why} changed since the review)` };
  }
  return r.verdict === 'agree'
    ? { key: 'agree', label: 'agree', cls: 'ok', file: r.file }
    : { key: 'disagree', label: 'disagree', cls: 'bad', file: r.file };
}

const isThm = (d) => d.kind === 'theorem' || d.kind === 'lemma';
// Fw.Flags.Part.mem_all -> Part.mem_all (the namespace after Fw is the module's own).
const short = (name) => { const p = name.split('.'); return p.slice(p.length > 2 ? 2 : 1).join('.'); };
const modFile = (m) => `${m.replace(/\./g, '/')}.lean`;
const modId = (m) => `mv-${m.replace(/^Fw\./, '').replace(/\./g, '-').toLowerCase()}`;
const modLabel = (m) => m.split('.').pop();

function heading(m) {
  const file = join(leanDir, modFile(m));
  const line = existsSync(file) ? readFileSync(file, 'utf8').split('\n').find((l) => /^# /.test(l)) : null;
  return line ? line.slice(2).trim() : m;
}

function entry(d) {
  const body = d.doc.replace(/\s+$/, '');
  const indent = Math.min(...body.split('\n').slice(1).filter((l) => l.trim()).map((l) => l.match(/^\s*/)[0].length), 99);
  const dedented = body.split('\n').map((l, n) => (n === 0 ? l : l.slice(Math.min(indent, l.match(/^\s*/)[0].length)))).join('\n');
  const segs = segments(dedented);
  if (!segs.some((s) => s.math)) throw new Error(`${d.name} (${d.module} l.${d.line}): no $$ math`);
  let firstText = true;
  const parts = segs.map((s) => {
    try {
      if (s.math) return `<div class="mv-math">${tex(s.math, true)}</div>`;
      const cls = firstText ? 'mv-en' : 'mv-note';
      firstText = false;
      return `<p class="${cls}">${inline(s.text)}</p>`;
    } catch (e) {
      throw new Error(`${d.name} (${d.module} l.${d.line}): ${e.message}`);
    }
  });
  const st = d.status;
  const chip = st.key === 'agree' ? '' : `<span class="chip ${st.cls}"${st.file ? ` title="${esc(st.file)}"` : ''}>${st.label}</span>`;
  const kind = ['theorem', 'lemma', 'def'].includes(d.kind) ? '' : `<span class="chip">${d.kind}</span>`;
  return [
    `<div class="mv-entry${isThm(d) ? ' thm' : ''}" id="${entryId(d.name)}">`,
    `<div class="mv-head"><code class="mv-name" title="${esc(d.name)}">${esc(short(d.name))}</code>${kind}${chip}<span class="mv-loc">l.${d.line}</span></div>`,
    ...parts,
    '</div>',
  ].join('\n');
}

// Entry anchors sit on the entry itself, inside its closed <details>; a browser opens the ancestors on navigation.
const ids = new Map();
function entryId(name) {
  const id = 'mv-e-' + name.replace(/^Fw\./, '').replace(/[^A-Za-z0-9_.-]/g, (c) => `_${c.codePointAt(0).toString(16)}_`);
  if (ids.has(id) && ids.get(id) !== name) throw new Error(`entry id collision: ${name} and ${ids.get(id)}`);
  ids.set(id, name);
  return id;
}

const tally = (ds) => {
  const n = { agree: 0, disagree: 0, stale: 0, pending: 0 };
  for (const d of ds) n[d.status.key]++;
  return n;
};
const tallyText = (n) => [
  `${n.agree} agree`, `${n.disagree} disagree`, ...(n.stale ? [`${n.stale} stale`] : []), `${n.pending} pending`,
].join(' / ');

function render(mods, all, stamp) {
  const nThm = all.filter(isThm).length;
  const disagree = all.filter((d) => d.status.key === 'disagree');
  const out = [
    BEGIN,
    `<p class="mv-count">${all.length} declarations in ${mods.length} modules: ${nThm} theorems, ${all.length - nThm} definitions. Review: ${tallyText(tally(all))}. Generated from <span class="mono">lake exe mathview</span> on <span class="mono">lean/</span> (export <span class="mono">${stamp}</span>, a sha256 of every name, stmtHash and mathHash); formulas pre-rendered as MathML by KaTeX ${KATEX_VERSION}.</p>`,
    '<details>',
    '<summary>Notation</summary>',
    '<div class="tbl mv-notation"><table>',
    '<thead><tr><th>Symbol</th><th>Meaning</th></tr></thead>',
    '<tbody>',
    ...notation.map(([t, a, b]) => (t === null
      ? `<tr><td>${esc(a)}</td><td>${esc(b)}</td></tr>`
      : `<tr><td><span class="mv-i">${tex(t, false)}</span></td><td>${esc(a)}</td></tr>`)),
    '</tbody></table></div>',
    '</details>',
    ...(disagree.length ? [
      '<h2 id="mv-attention">Needs attention</h2>',
      `<p>${disagree.length} declarations where the reviewer disagrees with the docstring.</p>`,
      `<ul class="tight">${disagree.map((d) => `<li><a href="#${entryId(d.name)}"><code>${esc(short(d.name))}</code></a> <span class="mv-sub">${esc(modLabel(d.module))}</span></li>`).join('')}</ul>`,
    ] : []),
    '<h2 id="mv-modules">Modules</h2>',
    '<div class="tbl"><table>',
    '<thead><tr><th>Module</th><th>Theorems</th><th>Definitions</th><th>Agree</th><th>Disagree</th><th>Stale</th><th>Pending</th></tr></thead>',
    '<tbody>',
    ...mods.map((m) => {
      const n = tally(m.decls);
      const nt = m.decls.filter(isThm).length;
      return `<tr><td class="k"><a href="#${modId(m.name)}">${esc(modLabel(m.name))}</a></td><td>${nt}</td><td>${m.decls.length - nt}</td><td>${n.agree}</td><td>${n.disagree}</td><td>${n.stale}</td><td>${n.pending}</td></tr>`;
    }),
    '</tbody></table></div>',
    '<h2>All declarations</h2>',
    '<div class="mv-all">',
  ];
  for (const m of mods) {
    const thms = m.decls.filter(isThm);
    const defs = m.decls.filter((d) => !isThm(d));
    const n = tally(m.decls);
    out.push(
      `<details class="mv-mod">`,
      `<summary><span class="mv-modname">${esc(modLabel(m.name))}</span> <span class="mv-sub">${thms.length} theorems · ${defs.length} definitions · ${n.agree}/${m.decls.length} reviewed${n.disagree ? ` · ${n.disagree} disagree` : ''}${n.stale ? ` · ${n.stale} stale` : ''}</span></summary>`,
      `<div class="mv-modbody" id="${modId(m.name)}">`,
      `<div class="mv-modhead"><h3>${esc(modLabel(m.name))}</h3><span class="mv-sub">${esc(heading(m.name))}</span><span class="mv-file mono">${esc(modFile(m.name))}</span></div>`,
      ...thms.map(entry),
      ...(defs.length ? [`<details class="mv-defs"><summary>Definitions used (${defs.length})</summary>`, ...defs.map(entry), '</details>'] : []),
      '</div>',
      '</details>',
    );
  }
  out.push('</div>', END);
  return out.join('\n');
}

// The review panel above the view: chip, tally, records, axioms.
function renderReview(all, stamp) {
  const n = tally(all);
  const done = n.agree === all.length;
  const chipLabel = n.disagree ? `${n.disagree} disagree` : n.stale ? `${n.stale} stale` : n.pending ? 'review pending' : 'reviewed';
  const disagree = all.filter((d) => d.status.key === 'disagree');
  const view = 'math-view.html';
  const record = existsSync(join(root, FWCORE_RECORD))
    ? `<a href="../../${FWCORE_RECORD}">${esc(FWCORE_RECORD.split('/').pop())}</a>`
    : `<span class="mono">${esc(FWCORE_RECORD.split('/').pop())}</span> (not written yet)`;
  const clean = all.every((d) => d.sorryFree && d.axioms.every((a) => AXIOMS.includes(a)));
  const nThm = all.filter(isThm).length;
  return [
    RBEGIN,
    `<h3><a class="chip ${done ? 'ok' : n.disagree ? 'bad' : 'open'}" href="#mv-review">${chipLabel}</a> ${tallyText(n)}</h3>`,
    `<p>${all.length} declarations (${nThm} theorems) in ${new Set(all.map((d) => d.module)).size} modules. <a href="${view}">Open the full math view</a> (own page; one closed section per module).${disagree.length ? ` Disagreements: ${disagree.map((d) => `<a href="${view}#${entryId(d.name)}"><code>${esc(short(d.name))}</code></a>`).join(', ')}.` : ''}</p>`,
    `<p id="mv-review">Each declaration shows its status: <i>agree</i> or <i>disagree</i> from a math-reviewer record, <i>review stale</i> when the Lean statement or, for rows that carry a docstring hash, the docstring changed after the review, <i>review pending</i> when no record covers it yet. Record for <span class="mono">lean/</span>: ${record}. The protocol: write its own math from the Lean, then compare it clause by clause with the docstring (ℕ vs ℤ, every hypothesis, ≤ vs &lt;, rounding, empty lists, ties, direction of ⇒ and ⇔).</p>`,
    `<p>${clean
      ? `In export <span class="mono">${stamp}</span> all ${all.length} declarations (${nThm} theorems) are free of <code>sorry</code> and use only the standard axioms (<code>propext</code>, <code>Classical.choice</code>, <code>Quot.sound</code>), checked by <code>lake exe mathview --lint</code>.`
      : `In export <span class="mono">${stamp}</span> some declarations use <code>sorry</code> or a non-standard axiom.`} The kickoff sketch's 72 declarations were reviewed earlier (<a href="../../${SKETCH_RECORD}">72 agree / 0 disagree</a>); that record does not cover <span class="mono">lean/</span>.</p>`,
    REND,
  ].join('\n');
}

